"""Parity for the two ILO datasets (EMPLOY, COLBAR) against the legacy
cleaners, from the committed SDMX-JSON responses.

The golden files were generated by ``generate_worker_engagement_cases.py``
in the old virtualenv at the pinned commit, running the registered legacy
cleaner functions (``extract_ilo`` and ``filter_ilo`` underneath). Compared
exactly: identity set, value, unit, area coverage, year coverage.
"""

import pytest

from sspi.ingestion.ilo import REQUEST_PERIODS, parse_query
from sspi.metadata import CountryCatalog, MetadataCatalog
from tests.golden.parity import OBSERVATION_CASES, OBSERVATION_IDENTITY, assert_parity, load_cases, observation_record, source_fixtures
from tests.golden.worker_engagement import CASES, DATASETS, FixtureClient, normalized, responses

CATALOG = MetadataCatalog.load()
SSPI67 = set(CountryCatalog.load().group("SSPI67").members)


@pytest.fixture(scope="module", params=DATASETS)
def ilo(request):
    code = request.param
    return code, load_cases(OBSERVATION_CASES[code]), normalized()[code]


def test_golden_file_describes_this_dataset_and_its_legacy_request(ilo):
    code, case, _ = ilo
    source = CATALOG.dataset(code).source
    dataflow, key = parse_query(source.query_code)
    assert case["dataset_code"] == code
    assert (case["source_request"]["dataflow"], case["source_request"]["key"]) == (dataflow, key) and dataflow == source.organization_series_code
    assert case["source_request"]["url_params"] == [f"{name}={value}" for name, value in REQUEST_PERIODS[source.query_code]]
    assert [p.name for p in source_fixtures(case)] == [dict(CASES.values())[code]]


def test_observations_match_the_legacy_cleaner_exactly(ilo):
    code, case, result = ilo
    assert_parity(f"{code} observations", [observation_record(o) for o in result.observations], case["observations"], OBSERVATION_IDENTITY)
    assert len(result.observations) == {"ILO_EMPLOY_TO_POP": 2690, "ILO_COLBAR": 865}[code]
    assert {o.unit for o in result.observations} == {CATALOG.dataset(code).unit} == {{"ILO_EMPLOY_TO_POP": "Rate", "ILO_COLBAR": "Proportion"}[code]}  # the legacy labels


def test_nothing_is_skipped_or_missing_in_these_responses(ilo):
    _, case, result = ilo
    assert list(result.skipped_areas) == case["skipped_areas"] == [] and result.missing_values == case["empty_source_values"] == 0


def test_canonical_dimensions_are_the_ones_the_legacy_cleaner_filtered_on(ilo):
    code, case, result = ilo
    dimensions = CATALOG.dataset(code).source.dimensions
    assert dimensions == {"ILO_EMPLOY_TO_POP": {"SEX": "SEX_T", "AGE": "AGE_YTHADULT_Y15-64"}, "ILO_COLBAR": None}[code]
    for name, wanted in (dimensions or {}).items():
        assert case["series_dimensions"][name] == [wanted] and {o.provenance[name] for o in result.observations} == {wanted}
    assert {o.provenance["FREQ"] for o in result.observations} == {"A"}


def test_employment_coverage_is_every_area_from_2000_with_no_country_restriction():
    result = normalized()["ILO_EMPLOY_TO_POP"]
    areas = {o.country_code for o in result.observations}
    assert len(areas) == 211 and SSPI67 <= areas
    assert {"ANT", "KOS"} <= areas  # ILO codes that are not ISO 3166-1; the legacy cleaner kept them and so does this one
    assert (min(o.year for o in result.observations), max(o.year for o in result.observations)) == (2000, 2025)
    malaysia = {o.year: o.value for o in result.observations if o.country_code == "MYS"}
    assert malaysia[2022] == 66.538


def test_collective_bargaining_coverage_stops_in_2020_and_misses_ten_sspi_countries():
    result = normalized()["ILO_COLBAR"]
    areas = {o.country_code for o in result.observations}
    assert len(areas) == 99 and (min(o.year for o in result.observations), max(o.year for o in result.observations)) == (2000, 2020)
    assert sorted(SSPI67 - areas) == ["ARE", "DZA", "ECU", "IND", "IRN", "IRQ", "KWT", "NGA", "PAK", "SAU"]  # the ten listed, with no text, in the methodology file (COLBAR-1)
    structure = responses()[CATALOG.dataset("ILO_COLBAR").source.query_code]["data"]["structures"][0]
    unit = next(a for a in structure["attributes"]["series"] if a["id"] == "UNIT_MEASURE")
    assert [v["id"] for v in unit["values"]] == ["PT"]  # the source says percent; the legacy unit label is "Proportion" (COLBAR-2)
    assert (min(o.value for o in result.observations), max(o.value for o in result.observations)) == (0.4, 99.2)


def test_each_dataset_is_one_request():
    from sspi.ingestion.runner import fetch_and_normalize, resolve_datasets

    client = FixtureClient()
    _, fetches = fetch_and_normalize(resolve_datasets(list(DATASETS), CATALOG), client, metadata=CATALOG)
    assert list(fetches) == client.fetches == [CATALOG.dataset(code).source.query_code for code in DATASETS]
