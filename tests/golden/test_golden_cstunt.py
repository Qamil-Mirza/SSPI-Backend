def test_series_fill_methods_on_the_synthetic_gaps():
    fill = series_fill("synthetic_gaps")
    assert all(is_imputed(s) and s.unit == "Coefficient" for s in fill)  # CSTUNT-1: the impute route's unit literal
    by_method = Counter(s.inputs[0].provenance["imputation_method"] for s in fill)
    assert by_method == {"Forward Extrapolation": 29, "Backward Extrapolation": 20, "Linear Interpolation": 3}
    s = scores("synthetic_gaps")
    assert [y for y in range(2000, 2025) if (("MYS", y) in s) and is_imputed(s[("MYS", y)])] == [2000, 2001, 2002, 2003, 2004, 2021, 2022, 2023]
    assert ("MYS", 2024) not in s  # forward only to 2023
    assert {s[("USA", y)].inputs[0].provenance["imputation_method"] for y in (2010, 2011, 2012)} == {"Linear Interpolation"}
    india = {x.inputs[0].value for x in fill if x.country_code == "IND"}
    assert len(india) == 1 and sum(1 for x in fill if x.country_code == "IND") == 23  # one 2015 value carried over 23 years
    assert max(y for (c, y) in s if c == "NGA" and not is_imputed(s[(c, y)])) == 2005 and s[("NGA", 2023)].inputs[0].provenance["anchor_year"] == 2005


# --- D, E: regression training and fit ---------------------------------------------------------


@pytest.mark.parametrize("variant", VARIANTS)
def test_training_set_is_the_inner_join_the_legacy_fit_saw(variant):
    """GDP scores joined with observed CSTUNT scores by (country, year), pooled, in (country, year) order."""
    features = {(f.country_code, f.year): f.score for f in cstunt.gdp_feature_scores(normalized(variant)["WB_GDP_PERCAP_CURPRICE_USD"].observations)}
    targets = {(s.country_code, s.year): s.score for s in run(variant).observed_scores}
    training = [{"country_code": c, "year": y, "feature_score": features[(c, y)], "target_score": targets[(c, y)]} for c, y in sorted(set(features) & set(targets))]
    assert training == CASES[variant]["regression"]["training"]
    assert len(training) == {"verbatim": 418, "synthetic_gaps": 338}[variant]
    assert "PRK" not in {t["country_code"] for t in training}  # stunting data, no GDP


@pytest.mark.parametrize("variant", VARIANTS)
def test_fitted_parameters_equal_the_legacy_sklearn_fit_exactly(variant):
    regression = CASES[variant]["regression"]
    coefficient, intercept = fit_centered_least_squares((t["feature_score"] for t in regression["training"]), (t["target_score"] for t in regression["training"]))
    assert (coefficient, intercept) == (regression["coefficient"], regression["intercept"])
    assert (coefficient, intercept) == {"verbatim": (1.1494583602006676, 0.39946324246142784), "synthetic_gaps": (0.9346435547945705, 0.49488710839619365)}[variant]


# --- F, G: predictions -------------------------------------------------------------------------


@pytest.mark.parametrize("variant", VARIANTS)
def test_recipients_are_the_countries_with_no_cstunt_data(variant):
    recipients = sorted({s.country_code for s in predicted(variant)})
    assert recipients == CASES[variant]["regression"]["recipients"]
    with_data = {o.country_code for o in normalized(variant)["UNSDG_CSTUNT"].observations}
    with_gdp = {o.country_code for o in normalized(variant)["WB_GDP_PERCAP_CURPRICE_USD"].observations}
    assert recipients == sorted(with_gdp - with_data)  # derived from the data, not from a list
    assert recipients == {"verbatim": RECIPIENTS, "synthetic_gaps": sorted([*RECIPIENTS, "PAK"])}[variant]  # Pakistan: in the source, no value


@pytest.mark.parametrize("variant", VARIANTS)
def test_prediction_identities_and_inputs_match_legacy(variant):
    legacy = CASES[variant]["regression"]["prediction_inputs"]
    new = predicted(variant)
    assert [(s.country_code, s.year) for s in new] == [(p["country_code"], p["year"]) for p in legacy]
    assert [s.provenance["feature_score"] for s in new] == [p["feature_score"] for p in legacy]
    assert [s.provenance["raw_prediction"] for s in new] == [p["raw_prediction"] for p in legacy]


@pytest.mark.parametrize("variant", VARIANTS)
def test_predicted_scores_match_the_impute_route(variant):
    new = []
    for record, score in zip(score_level_records(predicted(variant)), predicted(variant)):
        lower, upper = score.provenance["goalposts"]
        new.append(dict(record, value=score.provenance["implied_value"], lower_goalpost=lower, upper_goalpost=upper))
    assert_parity(f"CSTUNT regression-predicted scores ({variant})", new, CASES[variant]["regression"]["predicted_scores"])
    assert all(0.0 <= s.score <= 1.0 and s.unit == "%" for s in predicted(variant))  # the observed scores' unit


def test_cstunt_2_predictions_cover_every_gdp_year():
    new = predicted("verbatim")
    assert len(new) == 609 and (min(s.year for s in new), max(s.year for s in new)) == (1960, 2025)
    austria = sorted(s.year for s in new if s.country_code == "AUT")
    assert austria == list(range(1960, 2026))  # 66 predicted years for a country with no stunting estimate at all
    s = scores()
    assert s[("CHE", 2024)].provenance["feature_score"] == 1.0  # 107,702 dollars: the GDP goalpost clamps at 100,000
    assert s[("LUX", 2023)].provenance["feature_score"] == 1.0 and s[("LUX", 2023)].score == s[("CHE", 2024)].score
    assert s[("AUT", 2023)].score == min(1.0, s[("AUT", 2023)].provenance["feature_score"] * CASES["verbatim"]["regression"]["coefficient"] + CASES["verbatim"]["regression"]["intercept"])


# --- H: final set, classification, provenance --------------------------------------------------


@pytest.mark.parametrize("variant", VARIANTS)
def test_final_identity_set_classification_and_provenance(variant):
    result = run(variant)
    case = CASES[variant]
    legacy = {(r["country_code"], r["year"]) for key in ("observed_scores", "series_fill_scores") for r in case[key]} | {(r["country_code"], r["year"]) for r in case["regression"]["predicted_scores"]}
    identities = [(s.country_code, s.year) for s in result.scores]
    assert len(identities) == len(set(identities)) and set(identities) == legacy and result.unscored == ()
    assert all(not is_imputed(s) and s.provenance == {} for s in result.observed_scores)
    for s in series_fill(variant):  # imputed through its input; the score itself was produced by the ordinary formula
        (source,) = s.inputs
        assert s.provenance == {} and source.dataset_code == "UNSDG_CSTUNT" and source.provenance["imputed"] is True and s.score == cstunt.score_cstunt(source.value)
    regression = case["regression"]
    for s in predicted(variant):  # imputed at score level; no observation fabricated
        assert s.inputs == () and s.computed == () and is_imputed(s)
        assert s.provenance["imputation_method"] == REGRESSION_IMPUTATION and s.provenance["imputation_distance"] == 0
        assert s.provenance["feature_indicator"] == "WB_GDP_PERCAP_CURPRICE_USD" and s.provenance["feature_transform"] == "goalpost(WB_GDP_PERCAP_CURPRICE_USD, 0, 100000)"
        assert s.provenance["regression_model"] == cstunt.REGRESSION_MODEL and s.provenance["imputation_details"] == cstunt.REGRESSION_DETAILS
        assert (s.provenance["coefficient"], s.provenance["intercept"], s.provenance["training_score_count"]) == (regression["coefficient"], regression["intercept"], len(regression["training"]))


