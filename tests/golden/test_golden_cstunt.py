def test_cstunt_dataset_is_the_modelled_stunting_share_of_children_under_five():
    source = CATALOG.dataset("UNSDG_CSTUNT").source
    assert (source.organization_code, source.query_code, source.organization_series_code) == ("UNSDG", "2.2.1", "SH_STA_STNT")
    assert source.dimensions == {"sex": "BOTHSEX", "age": "<5Y"} and "UNSDG_CSTUNT" in SUPPORTED_DATASETS
    case = load_cases(OBSERVATION_CASES["UNSDG_CSTUNT"])
    assert case["descriptions"] == ["Proportion of children moderately or severely stunted (%)"]
    observations = normalized()["UNSDG_CSTUNT"].observations
    assert len(observations) == 450 and {o.unit for o in observations} == {"PER_POP_U5"} == {o["unit"] for o in case["observations"]}
    assert {o.provenance["nature"] for o in observations} == {"M"}  # every value is a modelled estimate
    assert {o.year for o in observations} == set(range(2000, 2025)) and len({o.country_code for o in observations}) == 18
    rows = json.loads(UNSDG_FIXTURES["verbatim"].read_text())["data"]
    malaysia = {(r["series"], r["sex"]) for r in rows if r["geoAreaCode"] == "458"}
    assert malaysia == {("SH_STA_STNT", "BOTHSEX"), ("SH_STA_STNT", "FEMALE"), ("SH_STA_STNT", "MALE"), ("SH_STA_STNTN", "BOTHSEX")}
    assert {o.provenance["source_series"] for o in observations} == {"SH_STA_STNT"}  # the number of stunted children is another series
    assert sorted(code for code, _ in normalized()["UNSDG_CSTUNT"].skipped_areas) == ["1", "2"]  # World, Africa


def test_gdp_dataset_matches_the_legacy_cleaner_exactly():
    case = load_cases(OBSERVATION_CASES["WB_GDP_PERCAP_CURPRICE_USD"])
    dataset = CATALOG.dataset("WB_GDP_PERCAP_CURPRICE_USD")
