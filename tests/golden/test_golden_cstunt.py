"""Parity for WB_GDP_PERCAP_CURPRICE_USD and CSTUNT against the legacy cleaner
and BOTH legacy routes, stage by stage:

    A  source cleaning            UNSDG_CSTUNT in test_golden_unsdg.py; the facts
                                  specific to it and the GDP dataset here
    B  observed scoring           compute route
    C  series fill                impute route, stage 1 (inputs)
    D  regression training set    the identities the legacy fit saw
    E  fitted parameters          legacy sklearn coefficient and intercept
    F  predicted identities       recipients and years
    G  predicted scores           impute route, stage 2 (scores)
    H  final identity set, classification, provenance
    I  the situations in which the legacy route fails

Two inputs: the verbatim sample of the live 2.2.1 response, where every
country has every year 2000-2024 so the series fill adds nothing, and a
synthetic variant with year values blanked that exercises it
(``tests/fixtures/unsdg/2_2_1_synthetic_gaps.json``; never source evidence).

``unsdg_cstunt_cases.json``, ``wb_gdp_percap_curprice_usd_cases.json`` and
``cstunt_cases.json`` were generated by ``generate_healthcare_cases.py`` in
the old virtualenv at the pinned commit, running the registered legacy
cleaners and the ``compute_cstunt`` / ``impute_cstunt`` view functions
themselves, with the legacy scikit-learn fit observed through a recording
subclass. Every comparison is exact; no tolerance.
"""

