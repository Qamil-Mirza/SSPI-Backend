@pytest.mark.parametrize("variant", VARIANTS)
def test_observed_scores_match_the_compute_route(variant):
    result = run(variant)
    assert_parity(f"CSTUNT observed scores ({variant})", score_level_records(result.observed_scores), CASES[variant]["observed_scores"])
    assert not any(is_imputed(s) for s in result.observed_scores) and {s.unit for s in result.observed_scores} == {"%"}
    assert len(result.observed_scores) == {"verbatim": 450, "synthetic_gaps": 370}[variant]


def test_observed_scoring_alone_needs_no_gdp():
    observed_only = compute_indicator(IndicatorDefinition("CSTUNT", cstunt.score_cstunt, imputation=None, unit=cstunt.UNIT), normalized()["UNSDG_CSTUNT"].observations)
    assert observed_only.observed_scores == run().observed_scores and observed_only.imputed_scores == ()


def test_less_stunting_is_better_on_fifty_to_zero():
    assert cstunt.score_cstunt(50) == 0.0 and cstunt.score_cstunt(25) == 0.5 and cstunt.score_cstunt(0) == 1.0
    s = scores()
    assert s[("BDI", 2000)].inputs[0].value == 63.0 and s[("BDI", 2000)].score == 0.0  # above the lower goalpost: clamped
    assert s[("AUS", 2000)].inputs[0].value == 0.9 and s[("AUS", 2000)].score == (0.9 - 50) / (0 - 50)  # the smallest value
    zeros = Counter(x.country_code for x in run().observed_scores if x.score == 0.0)  # 50 % or more of children stunted
    assert zeros == {"BDI": 25, "YEM": 11, "PRK": 2, "IND": 1}


