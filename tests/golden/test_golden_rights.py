@pytest.mark.parametrize("indicator", sorted(INDICATORS))
def test_forward_only_to_2023_and_goalposts(indicator):
    s = by_identity(run(indicator).scores)
    aut = [y for (c, y), score in s.items() if c == "AUT" and is_imputed(score)]
    assert sorted(aut) == list(range(2016, 2024)) and s[("AUT", 2023)].inputs[0].provenance["imputation_distance"] == 8
    assert not [y for (c, y), score in s.items() if c in ("USA", "SSD") and is_imputed(score)]  # already past 2023
    assert ("PSG", 2006) not in s and s[("PSG", 2023)].inputs[0].provenance["anchor_year"] == 2010  # no backward fill
    assert not {("ZZB", 2023), ("DDR", 2023)} & set(s)  # no observation, nothing carried
    if indicator == "RULELW":
        assert ("MYS", 2001) not in s  # an empty run inside the series is not interpolated
        assert s[("NOR", 2010)].score == 1.0 and s[("AFG", 2001)].score == 0.0 and s[("AUT", 1999)].score == 1.0
    else:
        assert s[("NOR", 2010)].score == 1.0 and s[("NOR", 2011)].score == 0.0 and s[("NOR", 2023)].score == 0.0


@pytest.mark.parametrize("indicator", sorted(INDICATORS))
def test_carried_scores_keep_the_legacy_value_and_the_source_year_they_come_from(indicator):
    """The approved storage correction (RULELW-1/EDEMOC-1) changes no value: each carried score is the score of the
    country's latest observation, and its input records that year."""
    result = run(indicator)
    observed = {(s.country_code, s.year): s for s in result.observed_scores}
    for score in result.imputed_scores:
        (carried,) = score.inputs
        anchor = observed[(score.country_code, carried.provenance["anchor_year"])]
        assert anchor.year == max(y for c, y in observed if c == score.country_code)
        assert (carried.value, score.score) == (anchor.inputs[0].value, anchor.score) and carried.provenance["imputed"] is True
    assert {s.inputs[0].provenance["anchor_year"] for s in result.imputed_scores if s.country_code == "MYS"} == {2022}


@pytest.mark.parametrize("indicator", sorted(INDICATORS))
def test_legacy_storage_of_the_imputations_is_recorded_not_reproduced(indicator):
    """RULELW-1/EDEMOC-1, approved storage correction: legacy put the carried scores in the observed collection, a
    second impute run held each twice and a later compute run erased them. Here they are imputed scores, and a run
    replaces every score of the indicator, so rerunning gives the same rows."""
    storage = indicator_cases(indicator)["legacy_storage"]
    observed, imputed = len(run(indicator).observed_scores), len(run(indicator).imputed_scores)
    assert storage["compute_then_impute"]["sspi_indicator_data"] == observed + imputed and storage["compute_then_impute"]["sspi_imputed_data"] == 0
    assert storage["then_impute_again"]["sspi_indicator_data"] == observed + 2 * imputed
    rerun = compute_indicator(registry.get(indicator), normalized()[INDICATORS[indicator]].observations)
    assert rerun == run(indicator)


