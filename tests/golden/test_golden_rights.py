"""Parity for VDEM_RULELW, VDEM_EDEMOC, RULELW and EDEMOC against the pinned
legacy collector, cleaners and BOTH legacy routes of each indicator, on the
committed SYNTHETIC V-Dem archive (invented values in the V-Dem layout; the
original is not distributed, GOV-6): observations, the year window the
cleaners applied on the run's calendar year, the ``to_json`` representation
of values, V-Dem's own country identifiers, missing values, the legacy
invalid-input failures, observed scores, imputed scores (carried forward to
2023 only), units, identities, imputation provenance and the legacy score
functions on inputs no fixture holds.

The golden files were generated by ``generate_rights_cases.py`` in the old
virtualenv at the pinned commit, with the cleaners' clock fixed to
2026-10-26. Every comparison is exact; no tolerance. The same comparison on
the original archive is the opt-in ``test_golden_rights_real_data.py``.
"""

