@pytest.mark.parametrize("indicator", sorted(INDICATORS))
def test_golden_file_records_the_legacy_facts(indicator):
    definition, cases, module = registry.get(indicator), indicator_cases(indicator), MODULES[indicator]
    definition.check_against(CATALOG)
    assert cases["formula"] == f"goalpost({INDICATORS[indicator]}, 0, 1)" == cases["methodology_score_function"].replace("Score = ", "")
    assert cases["goalposts"] == [0, 1] == list(definition.goalposts)
    assert cases["unit"] == cases["imputed_unit"] == "Index" == definition.unit == module.UNIT
    assert cases["impute_route_exists"] is True and definition.imputes
    assert cases["series_fill"] == {"order": ["forward"], "forward_to": 2023, "backward_to": None, "interpolation": None, "series_id": ["CountryCode", "DatasetCode"], "impute_only": True}
    assert definition.imputation == SeriesFillThenScore(getattr(module, f"score_{indicator.lower()}"), (2000, 2023), steps=("forward",))
    assert cases["impute_route_inserts_into"] == "sspi_indicator_data" and APPROVED_STORAGE_CORRECTIONS[indicator].conflict == f"{indicator}-1"


