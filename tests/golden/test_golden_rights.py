@pytest.mark.parametrize("code", DATASETS)
def test_dataset_metadata_names_the_pinned_archive_and_the_column(code):
    dataset = CATALOG.dataset(code)
    source = dataset.source
    assert (source.organization_code, source.query_code, source.organization_series_code) == ("VDEM", VDEM_KEY, COLUMNS[code])
    assert dataset.unit == "Index" and code in SUPPORTED_DATASETS
    cases = dataset_cases(code)
    assert cases["requested_urls"] == [LEGACY_URL] == [ARCHIVES[VDEM_KEY].url]  # one download serves both datasets
    assert cases["raw_source_info"]["QueryCode"] == VDEM_KEY and cases["source_column"] == COLUMNS[code]
    assert cases["raw_documents"] == 1 and cases["raw_fragments"] == [None]  # small enough not to be fragmented


@pytest.mark.parametrize("code", DATASETS)
def test_observations_match_the_legacy_collector_and_cleaner_exactly(code):
    result = normalized()[code]
    cases = dataset_cases(code)
    assert_parity(f"{code} observations", [observation_record(o) for o in result.observations], cases["observations"], OBSERVATION_IDENTITY)
