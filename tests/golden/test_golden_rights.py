def by_identity(scores):
    return {(s.country_code, s.year): s for s in scores}


# --- the synthetic archive ----------------------------------------------------------------------


def test_the_committed_archive_is_exactly_the_builder_output_and_says_it_is_synthetic():
    module = builder()
    content = VDEM_ARCHIVE.read_bytes()
    assert module.build() == content
    members = module.members(content)
    assert list(members) == [module.MEMBER, *module.OTHER_MEMBERS]
    lines = members[module.MEMBER].decode("utf-8").splitlines()
    assert tuple(lines[0].split(",")) == module.HEADER and all(module.NOTE in line for line in lines[1:])


def test_no_original_vdem_file_is_in_the_repository():
    manifest = {line.split("  ", 1)[0] for line in (FIXTURES / "vdem" / "REAL_DATA.sha256").read_text().splitlines() if line.strip()}
    assert ARCHIVES[VDEM_KEY].sha256 in manifest
    present = {hashlib.sha256(p.read_bytes()).hexdigest() for p in (REPO_ROOT / "tests").rglob("*") if p.is_file()}
    assert not present & manifest, "a file pinned by REAL_DATA.sha256 is under tests/: original V-Dem data stays outside the repository (GOV-6)"


