@pytest.mark.parametrize("indicator", INDICATORS)
def test_observed_scores_match_the_compute_route(indicator):
    result = run(indicator)
    assert_parity(f"{indicator} observed scores", score_level_records(result.observed_scores), indicator_case(indicator)["observed_scores"])
    assert not any(is_imputed(s) for s in result.observed_scores) and {s.unit for s in result.observed_scores} == {UNITS[indicator][1]}
    assert len(result.observed_scores) == {"ATBRTH": 46, "DPTCOV": 87, "PHYSPC": 82}[indicator]


def test_goalpost_boundaries_and_extremes():
    a, d, p = scores("ATBRTH"), scores("DPTCOV"), scores("PHYSPC")
    assert [(a[("QMA", y)].inputs[0].value, a[("QMA", y)].score) for y in (2010, 2011, 2012)] == [(80.0, 0.0), (79.9, 0.0), (100.0, 1.0)]  # at, below, at the top
    assert a[("QMB", 2015)].score == 0.0 and not is_imputed(a[("QMB", 2015)])
    assert [(d[("QMA", y)].inputs[0].value, d[("QMA", y)].score) for y in range(2010, 2015)] == [(75.0, 0.0), (99.0, 0.96), (100.0, 1.0), (0.0, 0.0), (74.9, 0.0)]
    assert [(p[("QMA", y)].inputs[0].value, p[("QMA", y)].score) for y in (2011, 2012, 2013)] == [(72.0, 1.0), (70.0, 1.0), (140.0, 1.0)]  # above, at, an outlier: clamped
    assert (p[("QMC", 2008)].score, p[("QMC", 2009)].inputs[0].value, p[("QMC", 2009)].score) == (0.0, 0.13, 0.13 / 70)


