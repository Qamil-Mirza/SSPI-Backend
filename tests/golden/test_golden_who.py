@pytest.mark.parametrize("indicator", INDICATORS)
def test_observations_match_the_legacy_cleaner_exactly(indicator):
    result, case = normalized(indicator), dataset_case(indicator)
    assert_parity(f"WHO_{indicator} observations", [observation_record(o) for o in result.observations], case["observations"], OBSERVATION_IDENTITY)
    assert sorted(list(a) for a in result.skipped_areas) == case["skipped_areas"]
    assert result.missing_values == case["no_data_rows"] == {"ATBRTH": 2, "DPTCOV": 1, "PHYSPC": 1}[indicator]
    assert {o.unit for o in result.observations} == {UNITS[indicator][0]}
    assert {o.provenance["source_indicator"] for o in result.observations} == {INDICATORS[indicator]} and not any("source_dimensions" in o.provenance for o in result.observations)


@pytest.mark.parametrize("indicator", INDICATORS)
def test_every_aggregate_kind_is_skipped_and_codes_are_kept_as_served(indicator):
    assert {kind for _, kind in normalized(indicator).skipped_areas} == {"GLOBAL", "REGION", "WORLDBANKINCOMEGROUP", "UNREGION"}
    assert {o.country_code for o in normalized(indicator).observations} >= {"MYS", "AUT", "USA", "QMA"}  # user-assigned codes kept, as legacy kept them


def test_no_data_rows_are_dropped_and_zeros_are_kept():
    a, d, p = ({(o.country_code, o.year): o.value for o in normalized(i).observations} for i in INDICATORS)
    assert ("QMC", 2006) not in a and ("QMF", 2018) not in a and ("QMC", 2016) not in d and ("QMF", 2020) not in p  # "No data"
    assert a[("QMB", 2015)] == d[("QMA", 2013)] == p[("QMC", 2008)] == 0.0  # reported zeros


def test_the_value_is_the_unrounded_number():
    rows = payload("MDG_0000000025")["value"]
    rounded = [r for r in rows if r["SpatialDimType"] == "COUNTRY" and r["NumericValue"] is not None and r["Value"] != f"{r['NumericValue']:g}"]
    assert [(r["SpatialDim"], r["Value"], r["NumericValue"]) for r in rounded] == [("QME", "97", 96.7)]
    (observation,) = [o for o in normalized("ATBRTH").observations if o.country_code == "QME"]
    assert observation.value == 96.7 and observation.provenance["display_value"] == "97"


