"""Parity for the three WHO Healthcare datasets and indicators (ATBRTH,
DPTCOV, PHYSPC) against the legacy cleaner and every legacy route, on the
committed SYNTHETIC GHO fixtures: dataset identities, values and units;
observed and imputed scores with their inputs and imputation fields; units;
final identities, classification and the unscored set; the hard-coded ATBRTH
recipients; boundaries, extremes, zeros, "No data" rows and gaps;
empty-dataset behaviour.

WHO extracts are not distributed with the repository while redistribution
rights are open (docs/data-governance-review.md, GOV-1). The fixtures
``tests/fixtures/who/<code>_synthetic.json`` are invented GHO-shaped
responses written by ``tests/fixtures/who/build_synthetic.py``; the golden
files ``who_*_synthetic_cases.json`` and ``*_synthetic_cases.json`` were
generated by ``generate_who_cases.py`` in the old virtualenv at the pinned
commit, running the registered legacy cleaners and view functions on them.
Every comparison is exact; no tolerance. The same parity on real WHO data is
the opt-in module test_golden_who_real_data.py. Production ingestion always
reads the GHO API; synthetic data is test input only.
"""

import hashlib
import importlib.util
import json
from collections import Counter
from functools import cache
from pathlib import Path

import pytest

from sspi.errors import ImputationError
from sspi.imputation import REFERENCE_CLASS_AVERAGE, is_imputed
from sspi.indicators import atbrth, compute_indicator, dptcov, physpc, registry
from sspi.ingestion.runner import SUPPORTED_DATASETS, fetch_and_normalize, resolve_datasets
from sspi.ingestion.who import BASE_URL, GHOIndicatorData
from sspi.metadata import CountryCatalog, MetadataCatalog
from sspi.scoring import Observation
from tests.golden.parity import (
    INDICATOR_CASES,
    INTENTIONAL_DIVERGENCES,
    OBSERVATION_CASES,
    OBSERVATION_IDENTITY,
    PENDING_METHODOLOGY_DECISIONS,
    REPO_ROOT,
    assert_parity,
    legacy_inconsistency,
    load_cases,
    observation_record,
    score_level_records,
    source_fixtures,
)

FIXTURES = Path(__file__).parents[1] / "fixtures" / "who"
CATALOG = MetadataCatalog.load()
INDICATORS = {"ATBRTH": "MDG_0000000025", "DPTCOV": "WHS4_100", "PHYSPC": "HWF_0001"}
UNITS = {"ATBRTH": ("Percent", "%"), "DPTCOV": ("Percent", "%"), "PHYSPC": ("Doctors per 10000", "Rate")}  # dataset unit, score unit
GOALPOSTS = {"ATBRTH": (80, 100), "DPTCOV": (75, 100), "PHYSPC": (0, 70)}
FORMULAS = {"ATBRTH": atbrth.score_atbrth, "DPTCOV": dptcov.score_dptcov, "PHYSPC": physpc.score_physpc}
RECIPIENTS = ("CHE", "GBR", "NLD", "BEL", "SWE")


@cache
def builder():
    spec = importlib.util.spec_from_file_location("build_synthetic", FIXTURES / "build_synthetic.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def payload(code):
    return json.loads((FIXTURES / f"{code}_synthetic.json").read_text(encoding="utf-8"))


class FixtureClient:
    """Stands in for ``WHOClient``; counts fetches."""

    def __init__(self):
        self.fetches = []

    def fetch_indicator(self, code):
        self.fetches.append(code)
        data = payload(code)
        return GHOIndicatorData(code, BASE_URL + code, data["@odata.context"], 1, tuple(data["value"]))


@cache
def normalized(indicator):
    client = FixtureClient()
    ((dataset, result),), _ = fetch_and_normalize(resolve_datasets([f"WHO_{indicator}"], CATALOG), client, metadata=CATALOG)
    assert dataset.code == f"WHO_{indicator}" and client.fetches == [INDICATORS[indicator]]
    return result


@cache
def run(indicator):
    return compute_indicator(registry.get(indicator), normalized(indicator).observations)


def scores(indicator):
    return {(s.country_code, s.year): s for s in run(indicator).scores}


def dataset_case(indicator):
    return load_cases(OBSERVATION_CASES[f"WHO_{indicator}"])


def indicator_case(indicator):
    return load_cases(INDICATOR_CASES[indicator])


# --- the fixtures are synthetic, and no real WHO file is in the tree -------------------------------


def test_the_committed_fixtures_are_exactly_what_the_builder_writes():
    built = builder().build()
    assert sorted(built) == sorted(p.name for p in FIXTURES.glob("*.json")) == sorted(f"{code}_synthetic.json" for code in INDICATORS.values())
    for name, text in built.items():
        assert (FIXTURES / name).read_text(encoding="utf-8") == text, f"{name}: differs from build_synthetic.py's output"


@pytest.mark.parametrize("indicator", INDICATORS)
def test_every_fixture_row_is_marked_synthetic_and_every_golden_file_reads_a_synthetic_fixture(indicator):
    data = payload(INDICATORS[indicator])
    assert data["@odata.context"].startswith("https://example.invalid/")
    assert all(r["Comments"] == builder().NOTE and r["Date"] == builder().PLACEHOLDER_DATE for r in data["value"])
    for case in (dataset_case(indicator), indicator_case(indicator)):
        assert [p.relative_to(REPO_ROOT).as_posix() for p in source_fixtures(case)] == [f"tests/fixtures/who/{INDICATORS[indicator]}_synthetic.json"]


def test_no_real_who_file_is_in_the_repository_tree():
    """The real files (tests/fixtures/who/REAL_DATA.sha256) live outside the distributed tree (GOV-1)."""
    real = {line.split("  ", 1)[0] for line in (FIXTURES / "REAL_DATA.sha256").read_text().splitlines() if line.strip()}
    assert len(real) == 15
    present = [p for p in (REPO_ROOT / "tests").rglob("*.json") if hashlib.sha256(p.read_bytes()).hexdigest() in real]
    assert present == []


