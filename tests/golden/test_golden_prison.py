def by_identity(scores):
    return {(s.country_code, s.year): s for s in scores}


# --- the synthetic workbook ---------------------------------------------------------------------


def test_the_committed_workbook_is_exactly_the_builder_output_and_says_it_is_synthetic():
    module = builder("unodc")
    content = UNODC_WORKBOOK.read_bytes()
    assert module.build() == content
    cells = module.cells(content)
    assert list(cells) == ["data_cts_prisons_and_prisoners", "data_cts_prisoners_regional_est"]
    assert cells["data_cts_prisons_and_prisoners"][0][:2] == ("SYNTHETIC", module.NOTE) and cells["data_cts_prisons_and_prisoners"][2] == module.HEADER
    assert all(sheet[0][:2] == ("SYNTHETIC", module.NOTE) for sheet in cells.values())


def test_no_original_unodc_file_is_in_the_repository():
    manifest = {line.split("  ", 1)[0] for line in (FIXTURES / "unodc" / "REAL_DATA.sha256").read_text().splitlines() if line.strip()}
    assert WORKBOOKS[UNODC_KEY].sha256 in manifest
    present = {hashlib.sha256(p.read_bytes()).hexdigest() for p in (REPO_ROOT / "tests").rglob("*") if p.is_file()}
    assert not present & manifest, "a file pinned by REAL_DATA.sha256 is under tests/: original UNODC data must stay outside the repository (GOV-3)"


