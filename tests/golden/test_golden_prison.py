def test_observations_match_the_legacy_collector_and_cleaner_exactly():
    result = normalized()["UNODC_PRIPOP"]
    assert_parity("UNODC_PRIPOP observations", [observation_record(o) for o in result.observations], DATASET_CASES["observations"], OBSERVATION_IDENTITY)
    assert [list(s) for s in result.skipped_areas] == DATASET_CASES["skipped_areas"]
    assert {c for c, _ in result.skipped_areas} == {"GBR_E_W", "GBR_NI", "GBR_S", "IRQ_C", "IRQ_KRI"}  # Iraq's units are dropped, not combined (PRISON-4)
    assert result.missing_values == DATASET_CASES["empty_source_values"] == 2 and len(result.observations) == 112
    assert Counter(o.country_code for o in result.observations) == {"AUT": 25, "USA": 22, "QMC": 19, "GBR": 18, "MYS": 18, "QMD": 6, "QMB": 3, "QMA": 1}
    assert {o.unit for o in result.observations} == {"Rate per 100,000 population"} and DATASET_CASES["legacy_document_keys"] == ["CountryCode", "DatasetCode", "Unit", "Value", "Year"]


def test_the_united_kingdom_is_the_unweighted_mean_of_whichever_jurisdictions_report():
    """PRISON-1: the legacy cleaner averaged the three rates per year, unweighted, over the jurisdictions present."""
    assert REGIONAL_MEANS == {"UNODC_PRIPOP": {"GBR": ("GBR_NI", "GBR_E_W", "GBR_S")}}
    gbr = {o.year: o for o in normalized()["UNODC_PRIPOP"].observations if o.country_code == "GBR"}
    assert {str(y): o.provenance["unweighted_mean_of"] for y, o in gbr.items()} == DATASET_CASES["regional_mean_years"]
    assert gbr[2010].value == (142.5 + 135.0 + 81.25) / 3 == 119.58333333333333  # England and Wales, Scotland, Northern Ireland
    assert gbr[2021].provenance["unweighted_mean_of"] == ["GBR_E_W", "GBR_S"] and gbr[2021].value == 147.0  # Northern Ireland stopped: the mean jumps
    assert gbr[2022].provenance["unweighted_mean_of"] == ["GBR_E_W"] and gbr[2022].value == 148.5
    assert min(gbr) == 2005  # no jurisdiction before 2005


def test_values_keep_the_legacy_csv_round_trip_representation_and_zeros_are_kept():
    values = {(o.country_code, o.year): o for o in normalized()["UNODC_PRIPOP"].observations}
    malaysia = values[("MYS", 2015)]
    assert malaysia.value == 171.1234567890124 != 171.123456789012345  # to_csv wrote 16 significant digits; the cleaner read those
    assert malaysia.provenance["source_value"] == "171.1234567890124" and malaysia.provenance["source_sha256"] == hashlib.sha256(UNODC_WORKBOOK.read_bytes()).hexdigest()
    assert values[("QMB", 2010)].value == 0.0 and values[("QMB", 2011)].value == 0.0  # a reported zero is a value
    assert values[("AUT", 2016)].value == 93.0 and values[("AUT", 2017)].value == 92.25  # years written as text are read as years
    assert ("QME", 2012) not in values and ("MYS", 2010) not in values


