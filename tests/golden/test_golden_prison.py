def test_observed_scores_match_the_compute_route():
    result = run("PRISON")
    assert_parity("PRISON observed scores", score_level_records(result.observed_scores), CASES["observed_scores"])
    assert len(result.observed_scores) == 112 and not any(is_imputed(s) for s in result.observed_scores)
    assert sorted([u.country_code, u.year] for u in result.unscored) == CASES["incomplete_identities"] == []
    assert max(s.year for s in result.observed_scores) == 2024  # no year filter on observed scores


def test_imputed_scores_match_the_impute_route():
    result = run("PRISON")
    assert_parity("PRISON imputed scores", score_level_records(result.imputed_scores), CASES["imputed_scores"])
    assert len(result.imputed_scores) == 105 and all(is_imputed(s) for s in result.imputed_scores)
    methods = Counter(s.inputs[0].provenance["imputation_method"] for s in result.imputed_scores)
    assert methods == {"Backward Extrapolation": 51, "ImputeReferenceClassAverage": 24, "Forward Extrapolation": 23, "Linear Interpolation": 7}
    assert {s.unit for s in result.scores} == {"Prisoners per 100,000 population"}


def test_china_gets_the_flat_mean_of_every_row_for_every_year():
    """PRISON-2: every area, every year (2003-2024 here), unweighted, including zeros and the UK mean."""
    observations = normalized()["UNODC_PRIPOP"].observations
    mean = sum(o.value for o in observations) / len(observations)
    (call,) = CASES["reference_class"]
    assert call == {"country_code": "CHN", "years": [2000, 2023], "item_type": "Dataset", "item_code": "UNODC_PRIPOP", "reference_count": 112, "mean": mean}
    china = [s for s in run("PRISON").scores if s.country_code == "CHN"]
    assert {s.year for s in china} == set(range(2000, 2024)) and all(is_imputed(s) for s in china)
    assert {(s.inputs[0].value, s.inputs[0].provenance["reference_observation_count"], s.score) for s in china} == {(mean, 112, prison.score_prison(mean))}


def test_china_with_observed_rows_raises_as_the_legacy_route_failed():
    probe = CASES["probe_china_observed"]
    assert probe["legacy_impute_error"] == "InvalidDocumentFormatError: Duplicate dataset document found (document 0)" and probe["imputed_china_years"] == []
    china = Observation("UNODC_PRIPOP", "CHN", 2010, 125.0, "Rate per 100,000 population", {})
    with pytest.raises(ImputationError, match=r"\['CHN'\] now have observed UNODC_PRIPOP rows"):
        compute_indicator(registry.get("PRISON"), (*normalized()["UNODC_PRIPOP"].observations, china))


def test_series_fill_and_goalposts():
    s = by_identity(run("PRISON").scores)
    assert (s[("QMA", 2000)].inputs[0].provenance["imputation_distance"], s[("QMA", 2023)].inputs[0].provenance["imputation_distance"]) == (15, 8)  # one year, carried both ways
    assert s[("GBR", 2000)].inputs[0].value == 116.66666666666667 and s[("GBR", 2023)].inputs[0].value == 148.5  # the one-jurisdiction 2022 mean carried to 2023
    assert s[("MYS", 2010)].inputs[0].provenance["imputation_method"] == "Linear Interpolation" and s[("MYS", 2010)].score == 0.745
    assert s[("USA", 2000)].score == 0.0 and s[("USA", 2003)].score == 0.0 and s[("QMD", 2023)].score == 0.0  # 700, exactly 540, 555
    assert s[("QMB", 2010)].score == 1.0 and s[("QMC", 2023)].score == 1.0 and s[("QMC", 2000)].score == 1.0  # 0, exactly 40, 35
    assert s[("AUT", 2024)].score == 0.906 and not is_imputed(s[("AUT", 2024)])


