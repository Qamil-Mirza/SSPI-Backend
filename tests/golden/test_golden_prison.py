"""Parity for UNODC_PRIPOP and PRISON against the pinned legacy collector,
cleaner and BOTH legacy routes, on the committed SYNTHETIC UNODC workbook
(invented data in the UNODC layout; the original is not distributed,
GOV-3): observations, the United Kingdom's unweighted mean, skipped areas,
missing values, the legacy invalid-input failures, observed scores, imputed
scores (forward to 2023, backward to 2000, interpolation, then China's
reference-class mean), units, identities and imputation provenance, and the
legacy score function on inputs no fixture holds.

``unodc_pripop_synthetic_cases.json`` and ``prison_synthetic_cases.json``
were generated by ``generate_public_safety_cases.py`` in the old virtualenv
at the pinned commit. Every comparison is exact; no tolerance. The same
comparison on the original workbook is the opt-in
``test_golden_public_safety_real_data.py``.
"""

