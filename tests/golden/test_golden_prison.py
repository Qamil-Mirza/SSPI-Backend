def test_golden_file_records_the_legacy_facts():
    definition = registry.get("PRISON")
    definition.check_against(CATALOG)
    assert CASES["formula"] == "goalpost(UNODC_PRIPOP, 540, 40)" == CASES["methodology_score_function"].replace("Score = ", "")
    assert CASES["goalposts"] == [540, 40] == list(definition.goalposts)
    assert CASES["unit"] == CASES["imputed_unit"] == "Prisoners per 100,000 population" == definition.unit == prison.UNIT
    assert CASES["impute_route_exists"] is True and definition.imputes
    assert CASES["series_fill"]["order"] == ["forward", "backward", "interpolate"] and (CASES["series_fill"]["forward_to"], CASES["series_fill"]["backward_to"]) == (2023, 2000)
    assert definition.imputation == SeriesFillThenScore(prison.score_prison, (2000, 2023), steps=("forward", "backward", "interpolate"), listed_recipients=("CHN",))


