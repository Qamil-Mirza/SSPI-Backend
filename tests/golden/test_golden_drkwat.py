"""Parity for WB_DRKWAT and DRKWAT against the legacy cleaner and the legacy
compute route on the committed World Bank sample: observations, skipped
areas, scores, unit, inputs and coverage.

``wb_drkwat_cases.json`` and ``drkwat_cases.json`` were generated by
``generate_infrastructure_cases.py`` in the old virtualenv at the pinned
commit, running the registered legacy cleaner and the ``compute_drkwat``
view function. Legacy DRKWAT has no impute route. Every comparison is exact;
no tolerance.
"""

from collections import Counter

from sspi.imputation import is_imputed
from sspi.indicators import compute_indicator, drkwat, registry
from sspi.ingestion.runner import SUPPORTED_DATASETS
from tests.golden.infrastructure import CATALOG, normalized, rows
from tests.golden.parity import INDICATOR_CASES, OBSERVATION_CASES, OBSERVATION_IDENTITY, assert_parity, load_cases, observation_record, score_records

DATASET_CASES = load_cases(OBSERVATION_CASES["WB_DRKWAT"])
CASES = load_cases(INDICATOR_CASES["DRKWAT"])


def result():
    return compute_indicator(registry.get("DRKWAT"), normalized()["WB_DRKWAT"].observations)


def test_dataset_is_the_jmp_safely_managed_drinking_water_share():
    dataset = CATALOG.dataset("WB_DRKWAT")
    assert DATASET_CASES["source_indicator"] == "SH.H2O.SMDW.ZS" == dataset.source.query_code == dataset.source.organization_series_code  # series code: PROVENANCE
    assert dataset.source.organization_code == "WB" and "WB_DRKWAT" in SUPPORTED_DATASETS and dataset.unit == "Percent"
    assert DATASET_CASES["descriptions"] == ["People using safely managed drinking water services (% of population)"]  # not basic or improved water


def test_observations_match_the_legacy_cleaner_exactly():
    result_ = normalized()["WB_DRKWAT"]
    assert_parity("WB_DRKWAT observations", [observation_record(o) for o in result_.observations], DATASET_CASES["observations"], OBSERVATION_IDENTITY)
    assert [list(s) for s in result_.skipped_areas] == DATASET_CASES["skipped_areas"]
    assert result_.missing_values == DATASET_CASES["empty_source_values"] == 782 and len(result_.observations) == 274
    assert not any(r["value"] == 0 for r in rows("SH.H2O.SMDW.ZS"))


def test_golden_file_records_the_legacy_facts():
    definition = registry.get("DRKWAT")
    definition.check_against(CATALOG)
    assert CASES["formula"] == "goalpost(WB_DRKWAT, 0, 100)" and CASES["methodology_score_function"] == "Score = goalpost(WB_DRKWAT, 0, 100)"
    assert CASES["goalposts"] == [0, 100] == list(definition.goalposts)
    assert CASES["unit"] == drkwat.UNIT == definition.unit == "%"
    assert CASES["impute_route_exists"] is False and not definition.imputes
    assert definition.dataset_codes == ("WB_DRKWAT",) and definition.auxiliary_datasets == ()


def test_scores_match_the_compute_route_exactly():
    run = result()
    assert_parity("DRKWAT scores", score_records(run.observed_scores, imputation=False), CASES["scores"])
    assert len(run.observed_scores) == 274 and run.imputed_scores == () and run.unscored == () and CASES["incomplete_identities"] == []
    assert not any(is_imputed(s) for s in run.scores) and {s.unit for s in run.scores} == {"%"}


def test_missing_estimates_stay_missing():
    """DRKWAT-1: no imputation. A country without an estimate, or a year before its series starts, has no score."""
    scored = Counter(s.country_code for s in result().scores)
    assert scored == {"AUT": 25, "ETH": 25, "GBR": 25, "KWT": 25, "MYS": 25, "ROU": 25, "RUS": 25, "TZA": 25, "KOR": 23, "COG": 22, "USA": 20, "TCA": 9}
    assert not {"ARG", "SAU", "CHN", "AGO"} & set(scored)  # in the sample, every row null
    assert min(s.year for s in result().scores if s.country_code == "USA") == 2005


def test_scores_are_the_share_on_zero_to_one_hundred():
    s = {(x.country_code, x.year): x.score for x in result().scores}
    assert s[("MYS", 2023)] == 0.9462046640002271 and s[("AUT", 2023)] == 0.9889399713691059 and s[("USA", 2023)] == 0.975661860919937
    assert s[("GBR", 2000)] == s[("KWT", 2023)] == 1.0 and s[("GBR", 2023)] == 0.9983197037953011 and s[("TZA", 2000)] == 1.28395845752752 / 100
    assert CASES["empty_dataset"]["observed_scores"] == [] and compute_indicator(registry.get("DRKWAT"), ()).scores == ()
