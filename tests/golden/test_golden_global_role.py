def workbook_cells(content):
    import io

    import openpyxl

    book = openpyxl.load_workbook(io.BytesIO(content), read_only=True)
    try:
        return {sheet.title: list(sheet.iter_rows(values_only=True)) for sheet in book.worksheets}
    finally:
        book.close()


