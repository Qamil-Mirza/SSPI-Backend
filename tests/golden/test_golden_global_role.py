def test_the_preserved_legacy_route_reference_class_and_fills():
    observations = legacy_rows(normalized()["SIPRI_ARMEXP"].observations)
    s = by_identity(legacy_armexp(observations).scores)
    mean = sum(o.value for o in observations) / len(observations)  # every exporter, every year 1990-2025, zeros included
    for country in ("ARE", "BGD", "IRQ"):
        assert {y for (c, y) in s if c == country} == set(range(2000, 2024))
        assert {(s[(country, y)].inputs[0].value, s[(country, y)].score) for y in range(2000, 2024)} == {(mean, armexp.score_armexp(mean))}
    assert s[("BLR", 2023)].inputs[0].provenance["imputation_distance"] == 25  # Belarus's 1998 value carried 25 years
    assert s[("BRA", 2000)].inputs[0].provenance["imputation_method"] == "Backward Extrapolation" and ("BRA", 2025) in s  # carried back from 2024
    assert s[("VNM", 2005)].score == 0.001 and s[("VNM", 2006)].score == 0.0 and s[("VNM", 2007)].score == 0.0
    assert s[("USA", 2000)].score == 0.0 and not is_imputed(s[("USA", 2024)])


