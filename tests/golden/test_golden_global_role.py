def test_the_workbook_is_downloaded_or_read_from_a_configured_local_copy_and_must_match_the_pin(tmp_path):
    pinned = MILEX_WORKBOOKS[WORKBOOK_KEY]
    synthetic = MILEX_BOOK.read_bytes()
    table = {WORKBOOK_KEY: dataclasses.replace(pinned, sha256=hashlib.sha256(synthetic).hexdigest())}
    requested = []

    def serve(request):
        requested.append(str(request.url))
        return httpx.Response(200, content=synthetic)

    with httpx.Client(transport=httpx.MockTransport(serve)) as http:
        fetched = SIPRIClient(http=http, workbooks=table).fetch(WORKBOOK_KEY)
        assert (fetched.origin, fetched.content, requested) == (pinned.url, synthetic, [pinned.url])
        with pytest.raises(SourceResponseError, match="not the pinned 6cc3a30b.* no other edition is substituted"):
            SIPRIClient(http=http).fetch(WORKBOOK_KEY)  # the real pin: the synthetic bytes are refused
        with pytest.raises(SourceRequestError, match="no SIPRI query is configured for 'milex'"):
            SIPRIClient(http=http).fetch("milex")
    (tmp_path / pinned.filename).write_bytes(synthetic)
    local = PinnedWorkbookClient(table, local_directory=tmp_path).fetch_workbook(WORKBOOK_KEY)
    assert local.origin == f"local copy: {tmp_path / pinned.filename}" and local.content == synthetic
    with pytest.raises(SourceResponseError, match="not the pinned"):
        PinnedWorkbookClient(MILEX_WORKBOOKS, local_directory=tmp_path).fetch_workbook(WORKBOOK_KEY)
    with pytest.raises(SourceRequestError, match="the configured local copy .* is not at"):
        PinnedWorkbookClient(table, local_directory=tmp_path / "elsewhere").fetch_workbook(WORKBOOK_KEY)
    assert PinnedWorkbookClient(table).local_directory is None  # no default local path


