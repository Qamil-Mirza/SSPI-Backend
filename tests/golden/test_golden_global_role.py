def test_the_legacy_cleaner_labels_every_value_ten_or_eleven_years_late():
    """MILEXP-1: the 'Share of GDP' header runs 1990-2024; the cleaner numbers its value positions from 2000."""
    assert MILEX_CASES["share_of_gdp_header"][:3] == ["Country", "Notes", "1990.0"] and MILEX_CASES["share_of_gdp_header"][-1] == "2024.0"
    shifts = {}
    for row in MILEX_CASES["alignment"]:
        if not row["stored"] or row["name"] in ("Korea, North", "German Democratic Republic"):  # see below: their codes are other countries'
            continue
        published = {int(y): v for y, v in row["published"].items()}
        (shift,) = {int(y) - next(p for p, v in published.items() if v not in ("...", "xxx", ". .") and (float(v) * 100 if float(v) < 1 else float(v)) == value and (int(y) - p) in (10, 11)) for y, value in row["stored"].items()}
        shifts[row["name"]] = (row["notes"], shift)
    assert shifts["Algeria"] == ("§", 10) and shifts["Libya"] == ("‡§¶", 10)  # recognised note marks: the 1990 value is stored as 2000
    assert shifts["Austria"] == ("", 11) and shifts["United States of America"] == ("", 11)  # empty notes: the 1990 value is stored as 2001
    assert shifts["Ukraine"] == ("†", 11)  # an unrecognised mark is read as a (failed) value: 11 years
    assert max(d["year"] for d in MILEX_CASES["cleaned_observations"]) == 2024
    # SIPRI writes "Korea, North": the cleaner's "north korea" rule misses it and the legacy matcher gives KOR, the code of
    # "Korea, South"; it stores nothing only because SIPRI publishes no North Korean share of GDP.
    north = next(r for r in MILEX_CASES["alignment"] if r["name"] == "Korea, North")
    assert north["country_code"] == "KOR" and set(north["published"].values()) == {"..."}


