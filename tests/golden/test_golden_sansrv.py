"""Parity for WB_SANSRV and SANSRV against the legacy cleaner and BOTH legacy
routes on the committed World Bank sample: observations, observed scores
(compute route), imputed scores (impute route: forward to 2023, then
backward to 2000, no interpolation), units, identities and classification,
plus a variant of the sample with rows removed (an interior gap and a
single-year series), which the live source does not have.

``wb_sansrv_cases.json`` and ``sansrv_cases.json`` were generated by
``generate_infrastructure_cases.py`` in the old virtualenv at the pinned
commit, running the registered legacy cleaner and the ``compute_sansrv`` /
``impute_sansrv`` view functions themselves. Every comparison is exact; no
tolerance.
"""

from collections import Counter

import pytest

from sspi.imputation import is_imputed
from sspi.indicators import compute_indicator, registry, sansrv
from sspi.indicators.strategy import SeriesFillThenScore
from sspi.ingestion.runner import SUPPORTED_DATASETS
from tests.golden.infrastructure import CATALOG, normalized, rows
from tests.golden.parity import (
    INDICATOR_CASES,
    INTENTIONAL_DIVERGENCES,
    OBSERVATION_CASES,
    OBSERVATION_IDENTITY,
    PENDING_METHODOLOGY_DECISIONS,
    assert_parity,
    legacy_inconsistency,
    load_cases,
    observation_record,
    score_level_records,
)

DATASET_CASES = load_cases(OBSERVATION_CASES["WB_SANSRV"])
CASES = load_cases(INDICATOR_CASES["SANSRV"])
(VARIANT,) = CASES["variants"]
REMOVED = frozenset(tuple(r) for r in VARIANT["removed_observations"])


def observations(removed=frozenset()):
    return tuple(o for o in normalized()["WB_SANSRV"].observations if (o.country_code, o.year) not in removed)


@pytest.fixture(scope="module")
def result():
    return compute_indicator(registry.get("SANSRV"), observations())


def by_identity(scores):
    return {(s.country_code, s.year): s for s in scores}


# --- WB_SANSRV ----------------------------------------------------------------------------------


def test_dataset_is_the_jmp_basic_sanitation_share():
    dataset = CATALOG.dataset("WB_SANSRV")
    assert DATASET_CASES["source_indicator"] == "SH.STA.BASS.ZS" == dataset.source.query_code == dataset.source.organization_series_code  # series code: PROVENANCE
    assert dataset.source.organization_code == "WB" and "WB_SANSRV" in SUPPORTED_DATASETS and dataset.unit == "Percent"
    assert DATASET_CASES["descriptions"] == ["People using at least basic sanitation services (% of population)"]


def test_observations_match_the_legacy_cleaner_exactly():
    result_ = normalized()["WB_SANSRV"]
    assert_parity("WB_SANSRV observations", [observation_record(o) for o in result_.observations], DATASET_CASES["observations"], OBSERVATION_IDENTITY)
    assert [list(s) for s in result_.skipped_areas] == DATASET_CASES["skipped_areas"] and {c for c, _ in result_.skipped_areas} == {"AFE", "WLD", "XD", "XKX"}
    assert result_.missing_values == DATASET_CASES["empty_source_values"] == 701 and len(result_.observations) == 355
    assert not any(r["value"] == 0 for r in rows("SH.STA.BASS.ZS")) and {o.unit for o in result_.observations} == {"Percent"}
    assert (min(o.year for o in result_.observations), max(o.year for o in result_.observations)) == (2000, 2024)


# --- SANSRV -------------------------------------------------------------------------------------


def test_golden_file_records_the_legacy_facts():
    definition = registry.get("SANSRV")
    definition.check_against(CATALOG)
    assert CASES["formula"] == "goalpost(WB_SANSRV, 50, 100)" and CASES["methodology_score_function"] == "Score = goalpost(WB_SANSRV, 50, 100)"
    assert CASES["goalposts"] == [50, 100] == list(definition.goalposts)
    assert CASES["unit"] == CASES["imputed_unit"] == "Percent" == definition.unit == sansrv.UNIT
    assert CASES["impute_route_exists"] is True and definition.imputes
    assert CASES["series_fill"] == {"forward_to": 2023, "backward_to": 2000, "interpolation": None, "order": ["forward", "backward"], "series_id": ["CountryCode", "DatasetCode"]}
    assert definition.imputation == SeriesFillThenScore(sansrv.score_sansrv, (2000, 2023), steps=("forward", "backward"))
    assert definition.dataset_codes == ("WB_SANSRV",) and definition.recipient_group is None and definition.auxiliary_datasets == ()


def test_legacy_output_is_consistent_so_exact_parity_is_required():
    for variant in (CASES, VARIANT):
        assert legacy_inconsistency(variant) is None
        assert variant["legacy_output_conflicts"] == {"observed_and_imputed": [], "duplicate_imputed": []}
    assert not any(code == "SANSRV" for code, _ in list(INTENTIONAL_DIVERGENCES) + list(PENDING_METHODOLOGY_DECISIONS))


def test_observed_scores_match_the_compute_route(result):
    assert_parity("SANSRV observed scores", score_level_records(result.observed_scores), CASES["observed_scores"])
    assert len(result.observed_scores) == 355 and not any(is_imputed(s) for s in result.observed_scores)
    assert max(s.year for s in result.observed_scores) == 2024  # no year filter on observed scores


def test_imputed_scores_match_the_impute_route(result):
    assert_parity("SANSRV imputed scores", score_level_records(result.imputed_scores), CASES["imputed_scores"])
    assert len(result.imputed_scores) == 42 and all(is_imputed(s) for s in result.imputed_scores)
    assert {s.unit for s in result.scores} == {"Percent"} and result.unscored == ()


def test_only_extrapolation_carries_series_to_2000_and_2023(result):
    methods = Counter((s.country_code, s.inputs[0].provenance["imputation_method"]) for s in result.imputed_scores)
    assert methods == {("TCA", "Backward Extrapolation"): 16, ("SAU", "Backward Extrapolation"): 13, ("ARG", "Forward Extrapolation"): 7, ("COG", "Forward Extrapolation"): 2, ("RUS", "Backward Extrapolation"): 2, ("AGO", "Forward Extrapolation"): 1, ("ROU", "Backward Extrapolation"): 1}
    s = by_identity(result.scores)
    argentina = s[("ARG", 2023)].inputs[0]
    assert (argentina.value, argentina.provenance["anchor_year"], argentina.provenance["imputation_distance"]) == (94.8209557204549, 2016, 7)  # SANSRV-2: carried seven years
    assert s[("SAU", 2000)].inputs[0].provenance["anchor_year"] == 2013 and s[("ROU", 2000)].inputs[0].value == 74.1221850215514
    assert all(s.provenance == {} for s in result.scores)  # imputation is on the input, never on the score
    assert (min(x.year for x in result.imputed_scores), max(x.year for x in result.imputed_scores)) == (2000, 2023)


def test_an_interior_gap_is_not_interpolated_and_a_single_year_is_carried_both_ways():
    partial = compute_indicator(registry.get("SANSRV"), observations(REMOVED))
    assert VARIANT["name"] == "with_rows_removed" and len(REMOVED) == 11
    assert_parity("SANSRV observed scores, rows removed", score_level_records(partial.observed_scores), VARIANT["observed_scores"])
    assert_parity("SANSRV imputed scores, rows removed", score_level_records(partial.imputed_scores), VARIANT["imputed_scores"])
    s = by_identity(partial.scores)
    assert not any(("MYS", year) in s for year in (2010, 2011, 2012))  # no interpolation in the legacy route
    turks = {year: x.inputs[0].provenance["imputation_method"] for (country, year), x in s.items() if country == "TCA" and year != 2016}
    assert set(turks) == set(range(2000, 2024)) - {2016} and set(turks.values()) == {"Backward Extrapolation", "Forward Extrapolation"}


def test_goalposts_clamp_below_half_and_at_everyone(result):
    s = by_identity(result.scores)
    assert s[("ETH", 2000)].score == 0.0 and s[("ETH", 2000)].inputs[0].value == 2.9657663244498  # below 50 %
    assert s[("COG", 2023)].score == 0.0 and s[("AGO", 2023)].score == (50.2951359158799 - 50) / 50
    assert s[("KWT", 2015)].score == 1.0 and s[("MYS", 2023)].score == 0.9203828803046981
    assert sansrv.score_sansrv(50) == 0.0 and sansrv.score_sansrv(75) == 0.5 and sansrv.score_sansrv(100) == 1.0


def test_an_empty_dataset_scores_nothing_and_does_not_raise():
    assert CASES["empty_dataset"] == {"observed_scores": [], "legacy_impute_error": None}
    empty = compute_indicator(registry.get("SANSRV"), ())
    assert empty.scores == () and empty.unscored == ()
