# --- AQELEC -------------------------------------------------------------------------------------


def test_golden_file_records_the_legacy_facts():
    definition = registry.get("AQELEC")
    definition.check_against(CATALOG)
    assert CASES["formula"] == "0.5 * goalpost(WB_AVELEC, 0, 100) + 0.5 * goalpost(WEF_QUELEC, 1, 7)"
    assert CASES["input_goalposts"] == {"WB_AVELEC": list(aqelec.ACCESS_GOALPOSTS), "WEF_QUELEC": list(aqelec.QUALITY_GOALPOSTS)}
    assert CASES["score_function_parameters"] == list(definition.dataset_codes) == ["WB_AVELEC", "WEF_QUELEC"]
    assert CASES["unit"] == aqelec.UNIT == definition.unit == "Index" and CASES["impute_route_exists"] is False and not definition.imputes
    assert definition.goalposts is None and (CATALOG.indicator("AQELEC").lower_goalpost, CATALOG.indicator("AQELEC").upper_goalpost) == (None, None)


def test_scores_match_the_compute_route_exactly():
    result = run()
    assert_parity("AQELEC scores", score_records(result.observed_scores, imputation=False), CASES["observed_scores"])
    assert len(result.observed_scores) == 30 and result.imputed_scores == () and not any(is_imputed(s) for s in result.scores)
    assert {s.year for s in result.scores} == set(range(2007, 2018))  # the WEF series years only; nothing is carried past 2017


def test_incomplete_groups_match_the_compute_route():
    result = run()
    assert sorted([u.country_code, u.year] for u in result.unscored) == CASES["incomplete_identities"]
    assert sorted([u.country_code, u.year, sorted(o.dataset_code for o in u.inputs)] for u in result.unscored) == CASES["incomplete_groups"]
    assert Counter(tuple(g[2]) for g in CASES["incomplete_groups"]) == {("WB_AVELEC",): 179, ("WEF_QUELEC",): 16} and {u.reason for u in result.unscored} == {UnscoredReason.MISSING_DATASETS}
    unscored = {(u.country_code, u.year): u for u in result.unscored}
    assert unscored[("MYS", 2009)].details == ("WEF_QUELEC",) and unscored[("QMA", 2012)].details == ("WB_AVELEC",)  # a survey gap; an economy with no access data
    assert all(("USA", y) in unscored for y in range(2018, 2025)) and not any(c == "NER" for c, _ in scores_by_identity())  # no quality value, no score


def scores_by_identity():
    return {(s.country_code, s.year): s.score for s in run().scores}


def test_boundaries_and_values():
    s = scores_by_identity()
    assert s[("USA", 2017)] == 1.0 and s[("TCD", 2007)] == 0.5 * 5.5 / 100 + 0.0  # access 100 % and quality 7; quality 1
    assert s[("MYS", 2010)] == 0.5 * (99.5 / 100) + 0.5 * ((5.123456789012345 - 1) / 6) == 0.8411213990843621
    assert s[("MYS", 2013)] == 0.748 and s[("AUT", 2015)] == 0.9583333333333333


@pytest.mark.parametrize("case", CASES["score_function_cases"], ids=lambda c: c["case"])
def test_the_score_function_matches_the_legacy_lambda_on_edge_inputs(case):
    assert aqelec.score_aqelec(**case["inputs"]) == case["score"]


