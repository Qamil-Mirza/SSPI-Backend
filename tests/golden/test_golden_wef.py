"""Parity for WEF_QUELEC, WB_AVELEC and AQELEC against the pinned legacy
collector, cleaners and compute route, on the committed SYNTHETIC WEF
workbook (invented data in the WEF layout; the original is not distributed,
GOV-2) and the committed World Bank sample: observations, missing values,
the legacy invalid-input failures, scores, inputs, incomplete groups, and
the legacy score function on inputs no fixture holds.

``wef_quelec_synthetic_cases.json``, ``wb_avelec_cases.json`` and
``aqelec_synthetic_cases.json`` were generated by ``generate_wef_cases.py``
in the old virtualenv at the pinned commit. Every comparison is exact; no
tolerance. The same comparison on the original workbook is the opt-in
``test_golden_wef_real_data.py``.
"""

import hashlib
import importlib.util
import json
from collections import Counter
from functools import cache
from pathlib import Path

import pytest

from sspi.errors import DuplicateObservationError, NormalizationError
from sspi.imputation import is_imputed
from sspi.indicators import aqelec, compute_indicator, registry
from sspi.ingestion.runner import SUPPORTED_DATASETS, fetch_and_normalize, resolve_datasets
from sspi.ingestion.wef import WORKBOOKS, WEFWorkbook, legacy_unit, normalize_wef_dataset
from sspi.metadata import MetadataCatalog
from sspi.scoring import UnscoredReason
from tests.golden.parity import INDICATOR_CASES, OBSERVATION_CASES, OBSERVATION_IDENTITY, REPO_ROOT, assert_parity, load_cases, observation_record, score_records

FIXTURES = REPO_ROOT / "tests" / "fixtures"
WORKBOOK = FIXTURES / "wef" / "WEF-GCIHH_synthetic.xlsx"
KEY = "WEF-GCIHH_2023-07-17"
CATALOG = MetadataCatalog.load()
WEF_CASES = load_cases(OBSERVATION_CASES["WEF_QUELEC"])
WB_CASES = load_cases(OBSERVATION_CASES["WB_AVELEC"])
CASES = load_cases(INDICATOR_CASES["AQELEC"])


def builder():
    spec = importlib.util.spec_from_file_location("wef_build_synthetic", FIXTURES / "wef" / "build_synthetic.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def workbook(content: bytes) -> WEFWorkbook:
    return WEFWorkbook(KEY, WORKBOOKS[KEY], hashlib.sha256(content).hexdigest(), content)


class Sources:
    """The World Bank and WEF clients, answering from the committed fixtures."""

    def __init__(self):
        self.fetches = []

    def fetch_indicator(self, indicator):
        self.fetches.append(indicator)
        return json.loads((FIXTURES / "wb" / f"{indicator}_sample.json").read_text(encoding="utf-8"))[1]

    def fetch_workbook(self, key):
        self.fetches.append(key)
        return workbook(WORKBOOK.read_bytes())


@cache
def normalized():
    sources = Sources()
    results, fetches = fetch_and_normalize(resolve_datasets(["WB_AVELEC", "WEF_QUELEC"], CATALOG), {"WB": sources, "WEF": sources}, metadata=CATALOG)
    assert fetches == ("EG.ELC.ACCS.ZS", KEY) == tuple(sources.fetches)
    return {dataset.code: result for dataset, result in results}


@cache
def run():
    results = normalized()
    return compute_indicator(registry.get("AQELEC"), results["WB_AVELEC"].observations + results["WEF_QUELEC"].observations)


# --- the synthetic workbook ---------------------------------------------------------------------


def test_the_committed_workbook_is_exactly_the_builder_output_and_says_it_is_synthetic():
    module = builder()
    content = WORKBOOK.read_bytes()
    assert module.build() == content and hashlib.sha256(content).hexdigest() == WEF_CASES["workbook_sha256"] and len(content) == WEF_CASES["workbook_bytes"]
    cells = module.cells(content)
    assert list(cells) == ["Data", "Indicator Metadata", "Dataset Metadata"] and cells["Data"][0] == module.HEADER
    assert module.NOTE in json.dumps(cells["Dataset Metadata"]) and all(module.NOTE in row[2] for row in cells["Indicator Metadata"][1:])


def test_no_original_wef_file_is_in_the_repository():
    manifest = {line.split("  ", 1)[0] for line in (FIXTURES / "wef" / "REAL_DATA.sha256").read_text().splitlines() if line.strip()}
    assert WORKBOOKS[KEY].sha256 in manifest
    present = {hashlib.sha256(p.read_bytes()).hexdigest() for p in (REPO_ROOT / "tests").rglob("*") if p.is_file()}
    assert not present & manifest, "a file pinned by REAL_DATA.sha256 is under tests/: original WEF data must stay outside the repository (GOV-2)"


# --- WEF_QUELEC ---------------------------------------------------------------------------------


def test_dataset_metadata_names_the_pinned_workbook_and_the_series():
    dataset = CATALOG.dataset("WEF_QUELEC")
    source = dataset.source
    assert (source.organization_code, source.query_code, source.organization_series_code, source.dimensions) == ("WEF", KEY, "WEF.GCIHH.EOSQ064", {"Attribute 1": "Value"})
    assert dataset.unit == "1-7 (best)" == legacy_unit("Quality of electricity supply, 1-7 (best)") and "WEF_QUELEC" in SUPPORTED_DATASETS
    assert WEF_CASES["source_url"] == WORKBOOKS[KEY].url and WEF_CASES["legacy_source_info"]["QueryCode"] == "WEF.GCIHH.EOSQ064"  # legacy recorded the series as query code


def test_observations_match_the_legacy_collector_and_cleaner_exactly():
    result = normalized()["WEF_QUELEC"]
    assert_parity("WEF_QUELEC observations", [observation_record(o) for o in result.observations], WEF_CASES["observations"], OBSERVATION_IDENTITY)
    assert len(result.observations) == 46 and result.skipped_areas == () and result.missing_values == WEF_CASES["empty_source_values"] == 31
    assert (WEF_CASES["sheet_rows"], WEF_CASES["selected_rows"]) == (21, 7)  # Rank rows and the road-quality indicator are filtered out
    assert Counter(o.country_code for o in result.observations) == {"QRA": 11, "USA": 11, "MYS": 10, "TCD": 6, "QMA": 5, "AUT": 3}  # QMB: every year blank
    assert WEF_CASES["units"] == ["1-7 (best)"] and WEF_CASES["value_types"] == ["float"] and all(isinstance(o.value, float) for o in result.observations)


def test_values_keep_their_full_precision_and_integer_cells_become_floats():
    values = {(o.country_code, o.year): o for o in normalized()["WEF_QUELEC"].observations}
    assert values[("MYS", 2010)].value == 5.123456789012345 and values[("MYS", 2013)].value == 4.0
    assert values[("USA", 2017)].value == 7.0 and values[("TCD", 2007)].value == 1.0
    assert ("MYS", 2009) not in values  # a blank cell is a missing value
    provenance = values[("MYS", 2013)].provenance
    assert (provenance["source_file"], provenance["source_sha256"], provenance["source_value"]) == (KEY, hashlib.sha256(WORKBOOK.read_bytes()).hexdigest(), "4.0")  # as the legacy cleaner saw it after its CSV round trip
    assert provenance["source_selection"] == {"Indicator ID": "WEF.GCIHH.EOSQ064", "Attribute 1": "Value"} and provenance["source_edition"] == WORKBOOKS[KEY].edition


@pytest.mark.parametrize("variant", [v["name"] for v in WEF_CASES["invalid_variants"]])
def test_inputs_the_legacy_clean_collection_refused_are_errors(variant):
    (recorded,) = [v for v in WEF_CASES["invalid_variants"] if v["name"] == variant]
    assert recorded["legacy_error"].startswith("InvalidDocumentFormatError")  # legacy stored nothing for the dataset
    error = DuplicateObservationError if variant == "duplicate_row" else NormalizationError
    with pytest.raises(error):
        normalize_wef_dataset(CATALOG.dataset("WEF_QUELEC"), workbook(builder().build(variant)))


def test_the_invalid_variants_recorded_are_the_builder_ones():
    assert [v["name"] for v in WEF_CASES["invalid_variants"]] == list(builder().VARIANTS)


