"""Observation parity for the Greenhouse Gases source datasets against the
legacy cleaners, on the committed fixtures: ``WB_POPULN`` (World Bank
``SP.POP.TOTL``), ``IEA_TCO2EM`` (IEA ``CO2BySector``, transport rows, times
10**9) and the two FAOSTAT Food Balances beef datasets. The general FAO
parity checks for ``UNFAO_BFPROD`` and ``UNFAO_BFCONS`` run in
``test_golden_fao_datasets.py``; here are the facts particular to them.

The golden files were generated by ``generate_ghg_cases.py`` in the old
virtualenv at the pinned commit, running the registered cleaners. Every
comparison is exact.
"""

import pytest

from sspi.ingestion import SUPPORTED_DATASETS
from sspi.metadata import CountryCatalog, MetadataCatalog
from tests.golden.ghg import co2_rows, fbs_rows, normalized, population_payload
from tests.golden.parity import OBSERVATION_CASES, OBSERVATION_IDENTITY, assert_parity, load_cases, observation_record, summary

SSPI67 = set(CountryCatalog.load().group("SSPI67").members)


def case(code):
    return load_cases(OBSERVATION_CASES[code])


@pytest.mark.parametrize("code", ["UNFAO_BFPROD", "UNFAO_BFCONS", "WB_POPULN", "IEA_TCO2EM"])
def test_observations_match_the_legacy_cleaner_exactly(code):
    new = [observation_record(o) for o in normalized()[code].observations]
    assert_parity(f"{code} observations", new, case(code)["observations"], OBSERVATION_IDENTITY)
    assert summary(new) == summary(case(code)["observations"])
    assert code in SUPPORTED_DATASETS


# --- WB_POPULN --------------------------------------------------------------------------------


def test_population_is_every_recognized_economy_and_year_with_the_legacy_unit():
    result, golden = normalized()["WB_POPULN"], case("WB_POPULN")
    assert len(result.observations) == 828 and {o.unit for o in result.observations} == {"Population"}  # the legacy literal; the API's unit is empty
    assert sorted({o.provenance["description"] for o in result.observations}) == golden["descriptions"] == ["Population, total"]
    assert (min(o.year for o in result.observations), max(o.year for o in result.observations)) == (1960, 2025)
    assert "BOL" in {o.country_code for o in result.observations} and "BOL" not in SSPI67  # no country filter


def test_population_skips_aggregates_and_kosovo_and_counts_nulls():
    result, golden = normalized()["WB_POPULN"], case("WB_POPULN")
    assert [list(a) for a in result.skipped_areas] == golden["skipped_areas"]
    assert result.skipped_areas == (("WLD", "World"), ("XKX", "Kosovo"), ("XY", "Not classified"))
    assert result.missing_values == golden["empty_source_values"] == 30  # Palestine's null years
    assert sum(1 for o in result.observations if o.country_code == "PSE") == 36
    assert len(population_payload()[1]) == 1056


# --- IEA_TCO2EM -------------------------------------------------------------------------------


def test_transport_co2_is_the_transport_series_times_ten_to_the_ninth():
    result, golden = normalized()["IEA_TCO2EM"], case("IEA_TCO2EM")
    dataset = MetadataCatalog.load().dataset("IEA_TCO2EM")
    assert golden["dimensions"] == {"seriesLabel": "Transport Sector"} == dataset.source.dimensions
    assert golden["source_units"] == ["MtCO2"] == [dataset.source.published_unit] and golden["source_flows"] == ["TOTTRANS"]
    assert dataset.source.value_multiplier == 10**9 and dataset.unit == "Tonnes C02 per inhabitant"  # the legacy label, kept (GTRANS-1)
    rows = {(r["country"], int(r["year"])): r for r in co2_rows() if r["seriesLabel"] == "Transport Sector"}
    for o in result.observations:
        source = rows[(o.country_code, o.year)]
        assert o.value == source["value"] * 10**9 and o.unit == "Tonnes C02 per inhabitant"
        assert (o.provenance["source_unit"], o.provenance["source_value"], o.provenance["value_multiplier"]) == ("MtCO2", source["value"], 10**9)
    assert {o.provenance["flow"] for o in result.observations} == {"TOTTRANS"}


def test_transport_co2_drops_other_sectors_non_iso_areas_and_zeros():
    result, golden = normalized()["IEA_TCO2EM"], case("IEA_TCO2EM")
    assert len(result.observations) == 305 and len({r["seriesLabel"] for r in co2_rows()}) == 9  # the other eight sectors (Austria's) are not selected
    assert [a for a, _ in result.skipped_areas] == golden["skipped_areas"] == ["GUYANA", "UNK", "WORLD"]
    assert result.missing_values == golden["empty_source_values"] + golden["zero_source_values"] == 5  # Cambodia's zero years, dropped as falsy
    assert golden["empty_source_values"] == 0 and {o.year for o in result.observations if o.country_code == "KHM"} == set(range(1995, 2025))
    assert max(o.year for o in result.observations if o.country_code == "PAK") == 2019  # the fixture ends Pakistan in 2019 (GTRANS extrapolation)
    assert "TWN" in {o.country_code for o in result.observations}  # an IEA area the World Bank has no population for


# --- the FAOSTAT Food Balances beef datasets ---------------------------------------------------


def test_production_is_bulk_element_5511_which_the_legacy_api_called_2510():
    golden, dataset = case("UNFAO_BFPROD"), MetadataCatalog.load().dataset("UNFAO_BFPROD")
    assert golden["legacy_api_element"] == "2510" and golden["source_filters"]["element_code"] == "5511" and dataset.source.query_code == "Domain=FBS;Element=5511;Item=2731"
    assert golden["source_elements"] == ["Production"] and golden["source_units"] == ["1000 t"]
    result = normalized()["UNFAO_BFPROD"]
    assert {o.unit for o in result.observations} == {"1000 t"} and {o.provenance["source_element"] for o in result.observations} == {"Production"}
    zeros = [o for o in result.observations if o.value == 0]
    assert len(zeros) == golden["zero_source_values"] == 5 and {o.country_code for o in zeros} == {"FSM"}  # zero production is kept, as the legacy jq cleaner kept it


def test_consumption_keeps_the_legacy_unit_label_over_the_published_one():
    golden, dataset = case("UNFAO_BFCONS"), MetadataCatalog.load().dataset("UNFAO_BFCONS")
    assert golden["source_units"] == ["kg/cap"] == [dataset.source.published_unit] and dataset.source.value_multiplier is None
    result = normalized()["UNFAO_BFCONS"]
    assert {o.unit for o in result.observations} == {"kg/capita/year"} and {o.provenance["source_unit"] for o in result.observations} == {"kg/cap"}
    rows = {(r["Area Code (M49)"], r["Year"]): r for r in fbs_rows() if r["Element Code"] == "645"}
    assert all(o.value == float(rows[("'" + o.provenance["source_m49_code"], str(o.year))]["Value"]) for o in result.observations)  # values unchanged


def test_beef_geography_and_coverage():
    for code in ("UNFAO_BFPROD", "UNFAO_BFCONS"):
        result = normalized()[code]
        countries = {o.country_code for o in result.observations}
        assert countries == {"AUT", "BEL", "CHN", "FSM", "KWT", "LUX", "MYS", "PAK", "TWN", "USA"}
        assert "SGP" not in countries  # Singapore is not in the Food Balances: the BEEFMK reference-class recipient
        assert {o.provenance["source_m49_code"] for o in result.observations if o.country_code == "CHN"} == {"156"}  # China, mainland; FAO's broader China is skipped
        assert [a for a, _ in result.skipped_areas] == ["351", "5400", "5000"] and result.missing_values == 0
        assert (min(o.year for o in result.observations), max(o.year for o in result.observations)) == (2010, 2023)
    assert {(r["Item Code"], r["Element Code"]) for r in fbs_rows()} == {("2731", "5511"), ("2731", "645"), ("2731", "5611"), ("2501", "511")}  # other elements and items present, not selected
