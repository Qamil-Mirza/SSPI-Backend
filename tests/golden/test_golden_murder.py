"""Parity for WB_MURDER and MURDER against the legacy cleaner and BOTH legacy
routes on the committed World Bank sample: observations, skipped areas,
missing values (zeros included), observed scores (compute route), imputed
scores (impute route: interpolate, then forward to 2023, then backward to
2000), units, identities and imputation provenance, and the legacy score
function on inputs no fixture holds.

``wb_murder_cases.json`` and ``murder_cases.json`` were generated by
``generate_public_safety_cases.py`` in the old virtualenv at the pinned
commit, running the registered legacy cleaner and the ``compute_murder`` /
``impute_murder`` view functions themselves. Every comparison is exact; no
tolerance.
"""

from collections import Counter

import pytest

from sspi.imputation import is_imputed
from sspi.indicators import compute_indicator, murder, registry
from sspi.indicators.strategy import SeriesFillThenScore
from sspi.ingestion.runner import SUPPORTED_DATASETS
from tests.golden.parity import (
    INDICATOR_CASES,
    INOPERATIVE_IMPUTE_ROUTES,
    INTENTIONAL_DIVERGENCES,
    OBSERVATION_CASES,
    OBSERVATION_IDENTITY,
    PENDING_METHODOLOGY_DECISIONS,
    assert_parity,
    legacy_inconsistency,
    load_cases,
    observation_record,
    score_level_records,
)
from tests.golden.public_safety import CATALOG, WB_SAMPLE, normalized, run

DATASET_CASES = load_cases(OBSERVATION_CASES["WB_MURDER"])
CASES = load_cases(INDICATOR_CASES["MURDER"])


def by_identity(scores):
    return {(s.country_code, s.year): s for s in scores}


# --- WB_MURDER ----------------------------------------------------------------------------------


def test_dataset_is_the_world_bank_homicide_rate():
    dataset = CATALOG.dataset("WB_MURDER")
    assert DATASET_CASES["source_indicator"] == "VC.IHR.PSRC.P5" == dataset.source.query_code == dataset.source.organization_series_code  # series code: PROVENANCE
    assert dataset.source.organization_code == "WB" and "WB_MURDER" in SUPPORTED_DATASETS and dataset.unit == "Per 100,000 people"  # unit: PROVENANCE
    assert DATASET_CASES["descriptions"] == ["Intentional homicides (per 100,000 people)"]
    assert DATASET_CASES["generated_from"]["fixture"] == str(WB_SAMPLE.relative_to(WB_SAMPLE.parents[3]))


def test_observations_match_the_legacy_cleaner_exactly():
    result = normalized()["WB_MURDER"]
    assert_parity("WB_MURDER observations", [observation_record(o) for o in result.observations], DATASET_CASES["observations"], OBSERVATION_IDENTITY)
    assert [list(s) for s in result.skipped_areas] == DATASET_CASES["skipped_areas"] == [["CHI", "Channel Islands"], ["WLD", "World"], ["XD", "High income"], ["XKX", "Kosovo"]]
    assert result.missing_values == DATASET_CASES["empty_source_values"] == 759 and len(result.observations) == 297
    assert {o.unit for o in result.observations} == {"Per 100,000 people"}
    assert (min(o.year for o in result.observations), max(o.year for o in result.observations)) == (1990, 2023)


def test_a_reported_zero_is_dropped_as_missing_as_the_legacy_cleaner_did():
    """MURDER-1: the shared World Bank cleaner drops every falsy value, so a year with no recorded homicide is missing."""
    observed = {(o.country_code, o.year) for o in normalized()["WB_MURDER"].observations}
    assert DATASET_CASES["zero_values_dropped"] == [["ISL", 2006], ["LIE", 2007], ["LIE", 2009], ["MLT", 2006]]
    assert not observed & {tuple(z) for z in DATASET_CASES["zero_values_dropped"]}
    assert {("ISL", 2005), ("ISL", 2007), ("MLT", 2005), ("MLT", 2007)} <= observed


# --- MURDER -------------------------------------------------------------------------------------


def test_golden_file_records_the_legacy_facts():
    definition = registry.get("MURDER")
    definition.check_against(CATALOG)
    assert CASES["formula"] == "goalpost(WB_MURDER, 20, 0)" == CASES["methodology_score_function"].replace("Score = ", "")
    assert CASES["goalposts"] == [20, 0] == list(definition.goalposts)
    assert CASES["unit"] == CASES["imputed_unit"] == "Index" == definition.unit == murder.UNIT
    assert CASES["impute_route_exists"] is True and definition.imputes
    assert CASES["series_fill"] == {"order": ["interpolate", "forward", "backward"], "forward_to": 2023, "backward_to": 2000, "interpolation": "every interior gap, any year", "series_id": ["CountryCode", "DatasetCode"]}
    assert definition.imputation == SeriesFillThenScore(murder.score_murder, (2000, 2023), steps=("interpolate", "forward", "backward"))
    assert definition.dataset_codes == ("WB_MURDER",) and definition.imputation.listed_recipients == ()


def test_legacy_output_is_consistent_so_exact_parity_is_required():
    assert legacy_inconsistency(CASES) is None and CASES["legacy_output_conflicts"] == {"observed_and_imputed": [], "duplicate_imputed": []}
    assert "variants" not in CASES and "MURDER" not in INOPERATIVE_IMPUTE_ROUTES
    assert not any(code == "MURDER" for code, _ in list(INTENTIONAL_DIVERGENCES) + list(PENDING_METHODOLOGY_DECISIONS))


def test_observed_scores_match_the_compute_route():
    result = run("MURDER")
    assert_parity("MURDER observed scores", score_level_records(result.observed_scores), CASES["observed_scores"])
    assert len(result.observed_scores) == 297 and not any(is_imputed(s) for s in result.observed_scores)
    assert sorted([u.country_code, u.year] for u in result.unscored) == CASES["incomplete_identities"] == []
    assert min(s.year for s in result.observed_scores) == 1990  # no year filter on observed scores


def test_imputed_scores_match_the_impute_route():
    result = run("MURDER")
    assert_parity("MURDER imputed scores", score_level_records(result.imputed_scores), CASES["imputed_scores"])
    assert len(result.imputed_scores) == 187 and all(is_imputed(s) for s in result.imputed_scores)
    assert {s.unit for s in result.scores} == {"Index"} and all(s.provenance == {} for s in result.scores)  # imputation is on the input
    methods = Counter(s.inputs[0].provenance["imputation_method"] for s in result.imputed_scores)
    assert methods == {"Linear Interpolation": 77, "Forward Extrapolation": 72, "Backward Extrapolation": 38}


def test_zeros_are_interpolated_and_interpolation_is_not_bounded_by_the_window():
    s = by_identity(run("MURDER").scores)
    iceland = s[("ISL", 2006)].inputs[0]  # the source reports 0 homicides (MURDER-1)
    assert (iceland.value, iceland.provenance["imputation_method"], iceland.provenance["imputation_distance"]) == (0.8262043549804514, "Linear Interpolation", 1)
    assert s[("ISL", 2006)].score == 0.9586897822509775 < 1.0
    assert s[("CHN", 1998)].inputs[0].provenance["imputation_method"] == "Linear Interpolation"  # 1998-2001 gap filled, before 2000 too
    assert min(x.year for x in run("MURDER").imputed_scores) == 1995 and max(x.year for x in run("MURDER").imputed_scores) == 2023


def test_single_observations_and_old_series_are_carried_the_whole_window():
    """MURDER-2: every country is carried to 2000 and 2023 however far its nearest observation is."""
    s = by_identity(run("MURDER").scores)
    ethiopia_2000, ethiopia_2023 = s[("ETH", 2000)].inputs[0], s[("ETH", 2023)].inputs[0]  # one observation, 2012
    assert ethiopia_2000.value == ethiopia_2023.value == 8.51054794891045 and (ethiopia_2000.provenance["imputation_distance"], ethiopia_2023.provenance["imputation_distance"]) == (12, 11)
    monaco = s[("MCO", 2023)].inputs[0]  # one observation, 2001
    assert (monaco.provenance["imputation_method"], monaco.provenance["imputation_distance"]) == ("Forward Extrapolation", 22)
    nigeria = s[("NGA", 2000)].inputs[0]  # first observation 2016, above the lower goalpost
    assert (nigeria.value, nigeria.provenance["imputation_distance"], s[("NGA", 2000)].score) == (32.4390092901434, 16, 0.0)
    assert s[("IRQ", 2023)].inputs[0].provenance["anchor_year"] == 2013 and s[("THA", 2023)].inputs[0].provenance["anchor_year"] == 2011


def test_goalposts_lower_is_better():
    s = by_identity(run("MURDER").scores)
    assert s[("VEN", 2016)].score == 0.0 and s[("VEN", 2016)].inputs[0].value == 56.5792047678519  # beyond 20
    assert s[("MYS", 2023)].score == 0.9632753784643061 and s[("USA", 2023)].score == 0.7118296029634675 and s[("AUT", 2023)].score == 0.9561904484444268
    assert murder.score_murder(20) == 0.0 and murder.score_murder(0) == 1.0 and murder.score_murder(10) == 0.5


@pytest.mark.parametrize("case", CASES["score_function_cases"], ids=lambda c: c["case"])
def test_the_score_function_matches_the_legacy_lambda_on_edge_inputs(case):
    assert murder.score_murder(case["input"]) == case["score"]


def test_an_empty_dataset_scores_nothing_and_does_not_raise():
    assert CASES["empty_dataset"] == {"observed_scores": [], "imputed_scores": [], "legacy_impute_error": None}
    empty = compute_indicator(registry.get("MURDER"), ())
    assert empty.scores == () and empty.unscored == ()
