"""Parity for the Inequality source datasets against the legacy cleaners, from
the committed fixtures: the two WID income-share datasets (ISHRAT) and the
World Bank Gini dataset (GINIPT).

The golden files were generated by ``generate_inequality_cases.py`` in the
old virtualenv at the pinned commit, running the registered legacy cleaner
functions. Compared exactly: identity set, value (for WID the legacy float32
representation), unit, country coverage, year coverage, skipped areas and
missing values.
"""

import pytest

from sspi.ingestion.wid import LEGACY_COUNTRY_GROUP, LEGACY_YEARS, series_selection
from sspi.metadata import CountryCatalog, MetadataCatalog
from tests.golden.inequality import WB_DATASET, WID_DATASETS, FixtureClients, normalized, wb_rows
from tests.golden.parity import OBSERVATION_CASES, OBSERVATION_IDENTITY, assert_parity, load_cases, observation_record, source_fixtures

CATALOG = MetadataCatalog.load()


@pytest.fixture(scope="module", params=WID_DATASETS)
def wid(request):
    code = request.param
    return code, load_cases(OBSERVATION_CASES[code]), normalized()[code]


def test_wid_golden_file_describes_this_dataset(wid):
    code, case, _ = wid
    selection = series_selection(CATALOG.dataset(code))
    assert case["dataset_code"] == code
    assert case["source_selection"] == {
        "archive": selection.archive,
        "variable": selection.variable,
        "percentile": selection.percentile,
        "years": list(LEGACY_YEARS),
        "country_group": LEGACY_COUNTRY_GROUP,
    }
    assert selection.variable == "sptincj992" and selection.archive == "wid_all_data"
    assert [p.name for p in source_fixtures(case)] == ["wid"]


def test_wid_observations_match_the_legacy_cleaner_exactly(wid):
    code, case, result = wid
    assert_parity(f"{code} observations", [observation_record(o) for o in result.observations], case["observations"], OBSERVATION_IDENTITY)
    assert len(result.observations) == 1650 and result.skipped_areas == () and result.missing_values == 0
    assert {o.unit for o in result.observations} == {CATALOG.dataset(code).unit.strip()}


def test_wid_coverage_is_the_legacy_country_group_and_year_range(wid):
    code, case, result = wid
    members = set(CountryCatalog.load().group("SSPI67").members)
    assert {o.country_code for o in result.observations} == members == {o["country_code"] for o in case["observations"]}
    assert {o.year for o in result.observations} == set(range(2000, 2025))  # 1998 and 1999 are in the fixture and are not kept


def test_wid_values_are_the_legacy_float32_representation_of_the_published_text(wid):
    """The legacy cleaner did not store the published decimal. The golden file records both; the new backend stores
    the legacy number and keeps the published text in provenance."""
    code, case, result = wid
    published = {(p["country_code"], p["year"]): p["published"] for p in case["published_values"]}
    legacy = {(o["country_code"], o["year"]): o["value"] for o in case["observations"]}
    assert all(o.provenance["source_value"] == published[(o.country_code, o.year)] and o.value == legacy[(o.country_code, o.year)] for o in result.observations)
    differing = [o for o in result.observations if o.value != float(o.provenance["source_value"])]
    assert len(differing) > 1600  # nearly every share: 0.1921 -> 0.1921000034
    assert all(abs(o.value - float(o.provenance["source_value"])) < 1e-7 for o in result.observations)  # a representation artefact, not a different number
    malaysia = next(o for o in result.observations if (o.country_code, o.year) == ("MYS", 2024))
    expected = {"WID_NINCSH_PRETAX_P0P50": ("0.1921", 0.1921000034), "WID_NINCSH_PRETAX_P90P100": ("0.3653", 0.3652999997)}[code]
    assert (malaysia.provenance["source_value"], malaysia.value) == expected


def test_both_wid_datasets_come_from_one_archive_fetch():
    from sspi.ingestion.runner import fetch_and_normalize, resolve_datasets

    clients = FixtureClients()
    _, fetches = fetch_and_normalize(resolve_datasets(list(WID_DATASETS), CATALOG), clients, metadata=CATALOG)
    assert fetches == ("wid_all_data",) and clients.fetches == [("WID", "wid_all_data")]


