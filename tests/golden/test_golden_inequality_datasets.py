@pytest.fixture(scope="module")
def wb():
    return load_cases(OBSERVATION_CASES[WB_DATASET]), normalized()[WB_DATASET]


def test_wb_golden_file_describes_this_dataset(wb):
    case, _ = wb
    source = CATALOG.dataset(WB_DATASET).source
    assert case["dataset_code"] == WB_DATASET and case["source_indicator"] == "SI.POV.GINI" == source.query_code == source.organization_series_code
    assert [str(p).endswith("tests/fixtures/wb/SI.POV.GINI_sample.json") for p in source_fixtures(case)] == [True]


def test_wb_observations_match_the_legacy_cleaner_exactly(wb):
    case, result = wb
    assert_parity("WB_GINIPT observations", [observation_record(o) for o in result.observations], case["observations"], OBSERVATION_IDENTITY)
    assert len(result.observations) == 1727
    assert {o.unit for o in result.observations} == {"GINI Coeffecient"}  # the legacy unit, spelling included
    assert sorted({o.provenance["description"] for o in result.observations}) == case["descriptions"] == ["Gini index"]


def test_wb_country_and_year_coverage_is_not_restricted(wb):
    """No SSPI67 filter and no year filter: every recognized economy and every year the source reports."""
    _, result = wb
    countries = {o.country_code for o in result.observations}
    members = set(CountryCatalog.load().group("SSPI67").members)
    assert len(countries) == 87 and len(countries - members) == 25 and "NAM" in countries
    assert members - countries == {"KWT", "NZL", "SAU", "SGP"}  # no Gini value in any year: the regression recipients
    assert (min(o.year for o in result.observations), max(o.year for o in result.observations)) == (1963, 2025)


def test_wb_skipped_areas_and_missing_values_match_legacy(wb):
    case, result = wb
    assert [list(area) for area in result.skipped_areas] == case["skipped_areas"]
    assert result.skipped_areas == (("AFE", "Africa Eastern and Southern"), ("WLD", "World"), ("XD", "High income"), ("XKX", "Kosovo"))
    assert result.missing_values == case["empty_source_values"] == 184
    valued_skipped = sum(1 for r in wb_rows() if r["value"] is not None and (r["countryiso3code"] or r["country"]["id"]) in {"AFE", "WLD", "XD", "XKX"})
    assert valued_skipped + result.missing_values + len(result.observations) + sum(1 for r in wb_rows() if r["value"] is None and (r["countryiso3code"] or r["country"]["id"]) in {"AFE", "WLD", "XD", "XKX"}) == len(wb_rows())
