"""Parity for ILO_FATINJ and FATINJ against the legacy cleaner and the legacy
compute route, from the committed ILOSTAT SDMX-JSON response (complete and
unmodified): observations, scores, units, identities, coverage.

``ilo_fatinj_cases.json`` and ``fatinj_cases.json`` were generated by
``generate_worker_wellbeing_cases.py`` in the old virtualenv at the pinned
commit, running the registered legacy cleaner (``extract_ilo`` and
``filter_ilo`` underneath) and the ``compute_fatinj`` view function itself.
Legacy FATINJ has no impute route. Every comparison is exact; no tolerance.

The response holds no null value and no aggregate area code; those paths of
the shared ILO adapter are covered with synthetic messages in
``tests/unit/test_ilo_adapter.py``.
"""

import json
from collections import Counter
from functools import cache
from pathlib import Path

import pytest

from sspi.indicators import compute_indicator, fatinj, registry
from sspi.ingestion.ilo import REQUEST_PERIODS, parse_query
from sspi.ingestion.runner import SUPPORTED_DATASETS, fetch_and_normalize, resolve_datasets
from sspi.metadata import CountryCatalog, MetadataCatalog
from tests.golden.parity import INDICATOR_CASES, OBSERVATION_CASES, OBSERVATION_IDENTITY, assert_parity, load_cases, observation_record, score_records, source_fixtures

FIXTURE = Path(__file__).parents[1] / "fixtures" / "ilo" / "DF_SDG_F881_SEX_MIG_RT.json"
CATALOG = MetadataCatalog.load()
SSPI67 = set(CountryCatalog.load().group("SSPI67").members)
QUERY = "Indicator=DF_SDG_F881_SEX_MIG_RT;Parameters="


class FixtureClient:
    """Stands in for ``ILOClient``; records the queries."""

    def __init__(self):
        self.queries = []

    def fetch_query(self, query_code):
        self.queries.append(query_code)
        return json.loads(FIXTURE.read_text(encoding="utf-8"))


@cache
def normalized():
    client = FixtureClient()
    ((dataset, result),), _ = fetch_and_normalize(resolve_datasets(["ILO_FATINJ"], CATALOG), client, metadata=CATALOG)
    assert dataset.code == "ILO_FATINJ" and client.queries == [QUERY]
    return result


@cache
def run():
    return compute_indicator(registry.get("FATINJ"), normalized().observations)


def scores():
    return {(s.country_code, s.year): s for s in run().scores}


@pytest.fixture(scope="module")
def dataset_case():
    return load_cases(OBSERVATION_CASES["ILO_FATINJ"])


@pytest.fixture(scope="module")
def indicator_case():
    return load_cases(INDICATOR_CASES["FATINJ"])


# --- ILO_FATINJ ---------------------------------------------------------------------------------


def test_golden_file_describes_this_dataset_and_its_legacy_request(dataset_case):
    source = CATALOG.dataset("ILO_FATINJ").source
    dataflow, key = parse_query(source.query_code)
    assert source.query_code == QUERY and (dataflow, key) == ("DF_SDG_F881_SEX_MIG_RT", "") == (dataset_case["source_request"]["dataflow"], dataset_case["source_request"]["key"])
    assert dataflow == source.organization_series_code and "ILO_FATINJ" in SUPPORTED_DATASETS
    assert dataset_case["source_request"]["url_params"] == [] and QUERY not in REQUEST_PERIODS  # the legacy collector sent no time window
    assert [p.name for p in source_fixtures(dataset_case)] == [FIXTURE.name]


def test_canonical_dimensions_are_the_ones_the_legacy_cleaner_filtered_on(dataset_case):
    result = normalized()
    assert CATALOG.dataset("ILO_FATINJ").source.dimensions == {"SEX": "SEX_T", "MIG": "MIG_STATUS_TOTAL"} == dataset_case["dimensions"]
    assert dataset_case["series_dimensions"] == {"FREQ": ["A"], "MEASURE": ["SDG_F881_RT"], "SEX": ["SEX_T", "SEX_M", "SEX_F"], "MIG": ["MIG_STATUS_TOTAL", "MIG_STATUS_MIGRANT", "MIG_STATUS_NONMIG"]}
    assert {(o.provenance["SEX"], o.provenance["MIG"], o.provenance["MEASURE"], o.provenance["FREQ"]) for o in result.observations} == {("SEX_T", "MIG_STATUS_TOTAL", "SDG_F881_RT", "A")}


def test_observations_match_the_legacy_cleaner_exactly(dataset_case):
    result = normalized()
    assert_parity("ILO_FATINJ observations", [observation_record(o) for o in result.observations], dataset_case["observations"], OBSERVATION_IDENTITY)
    assert len(result.observations) == 457 and {o.unit for o in result.observations} == {"Rate per 100,000"} == {CATALOG.dataset("ILO_FATINJ").unit}  # the legacy label
    assert list(result.skipped_areas) == dataset_case["skipped_areas"] == [] and result.missing_values == dataset_case["empty_source_values"] == 0


def test_coverage_zeros_outliers_and_territories():
    observations = normalized().observations
    areas = {o.country_code for o in observations}
    assert len(areas) == 103 and (min(o.year for o in observations), max(o.year for o in observations)) == (2000, 2024)
    assert {"GLP", "GUF", "HKG", "IMN", "MAC", "NCL", "PRI", "PSE", "REU", "TWN"} <= areas  # ILO area codes kept as published, no country filter
    assert len(areas & SSPI67) == 53 and sorted(SSPI67 - areas) == ["ARE", "BGD", "CHN", "ETH", "IDN", "IRN", "IRQ", "KEN", "KWT", "NGA", "PER", "VEN", "VNM"]
    per_area = Counter(o.country_code for o in observations)
    assert sum(1 for n in per_area.values() if n == 1) == 61  # most areas report a single year (FATINJ-1)
    zeros = sorted((o.country_code, o.year) for o in observations if o.value == 0)
    assert zeros == [("COL", 2017), ("GUF", 2014), ("ISL", 2011), ("ISL", 2012), ("ISL", 2013), ("ISL", 2021), *[("SMR", y) for y in range(2000, 2006)]]
    assert max(o.value for o in observations) == 556.992  # ZAF 2024, kept as published (FATINJ-2)


# --- FATINJ -------------------------------------------------------------------------------------


def test_golden_file_records_the_legacy_facts(indicator_case):
    definition = registry.get("FATINJ")
    definition.check_against(CATALOG)
    assert indicator_case["formula"] == "goalpost(ILO_FATINJ, 25, 0)" and indicator_case["methodology_score_function"] == "Score = goalpost(ILO_FATINJ, 25, 0)"
    assert indicator_case["goalposts"] == [25, 0] == list(definition.goalposts)
    assert indicator_case["unit"] == "Rate" == definition.unit == fatinj.UNIT
    assert indicator_case["impute_route_exists"] is False and not definition.imputes  # legacy FATINJ has no impute route
    assert definition.dataset_codes == ("ILO_FATINJ",) and definition.score_dependencies == ()


def test_scores_match_the_compute_route(indicator_case):
    result = run()
    assert_parity("FATINJ scores", score_records(result.scores, imputation=False), indicator_case["observed_scores"])
    assert len(result.scores) == 457 and result.imputed_scores == () and result.unscored == ()
    assert {s.unit for s in result.scores} == {"Rate"} and all(s.provenance == {} for s in result.scores)


def test_an_empty_dataset_scores_nothing(indicator_case):
    assert indicator_case["empty_dataset"] == {"observed_scores": []}
    assert compute_indicator(registry.get("FATINJ"), ()).scores == ()


def test_lower_is_better_on_twenty_five_to_zero():
    assert fatinj.score_fatinj(0) == 1.0 and fatinj.score_fatinj(12.5) == 0.5 and fatinj.score_fatinj(25) == 0.0 and fatinj.score_fatinj(50) == 0.0
    s = scores()
    assert s[("ISL", 2011)].inputs[0].value == 0.0 and s[("ISL", 2011)].score == 1.0  # a reported zero scores 1
    assert s[("CUB", 2010)].inputs[0].value == 25.0 and s[("CUB", 2010)].score == 0.0  # exactly the lower goalpost
    assert s[("ZAF", 2024)].score == 0.0 == s[("IND", 2005)].score  # 557 and 133 per 100,000: clamped by the goalpost only
    assert s[("USA", 2023)].score == fatinj.score_fatinj(3.5) and s[("AUT", 2024)].score > s[("USA", 2023)].score > s[("MYS", 2022)].score


def test_nothing_is_imputed_so_a_country_is_scored_only_in_reported_years():
    s = scores()
    assert [y for c, y in s if c == "MYS"] == [2022] and [y for c, y in s if c == "AUT"] == [2024] and [y for c, y in s if c == "USA"] == [2023]
    assert not any(c == "CHN" for c, _ in s)  # an SSPI67 member the ILO does not report has no FATINJ score at all
