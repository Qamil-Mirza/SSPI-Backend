"""Parity for UNEMPB against BOTH legacy routes on the committed UN SDG 1.3.1
sample: observed scores (compute route), imputed scores (impute route:
series fill on the input, then the hard-coded Iceland reference class),
units, identities and classification. The observations of
``UNSDG_BENFTS_UNEMP`` are compared with the legacy cleaner in
``test_golden_unsdg.py``, like every UN SDG dataset; the facts specific to
this dataset are checked here.

``unsdg_benfts_unemp_cases.json`` and ``unempb_cases.json`` were generated by
``generate_worker_wellbeing_cases.py`` in the old virtualenv at the pinned
commit, running the registered legacy cleaner and the ``compute_unempb`` /
``impute_unempb`` view functions themselves. Every comparison is exact; no
tolerance.
"""

import json
from collections import Counter
from functools import cache
from pathlib import Path

import pytest

from sspi.errors import ImputationError
from sspi.imputation import REFERENCE_CLASS_AVERAGE, is_imputed
from sspi.indicators import compute_indicator, registry, unempb
from sspi.indicators.strategy import SeriesFillThenScore
from sspi.ingestion.runner import SUPPORTED_DATASETS, fetch_and_normalize, resolve_datasets
from sspi.metadata import CountryCatalog, MetadataCatalog
from sspi.scoring import Observation
from tests.golden.parity import (
    INDICATOR_CASES,
    INTENTIONAL_DIVERGENCES,
    OBSERVATION_CASES,
    PENDING_METHODOLOGY_DECISIONS,
    assert_parity,
    legacy_inconsistency,
    load_cases,
    score_level_records,
)

FIXTURE = Path(__file__).parents[1] / "fixtures" / "unsdg" / "1_3_1_sample.json"
CATALOG = MetadataCatalog.load()
RECIPIENTS = ("ISL",)


@cache
def rows():
    return json.loads(FIXTURE.read_text(encoding="utf-8"))["data"]


class FixtureClient:
    """Stands in for ``UNSDGClient``; counts fetches."""

    def __init__(self):
        self.fetches = []

    def fetch_indicator(self, indicator):
        self.fetches.append(indicator)
        return rows()


@cache
def normalized():
    client = FixtureClient()
    ((dataset, result),), _ = fetch_and_normalize(resolve_datasets(["UNSDG_BENFTS_UNEMP"], CATALOG), client, metadata=CATALOG)
    assert dataset.code == "UNSDG_BENFTS_UNEMP" and client.fetches == ["1.3.1"]
    return result


@cache
def run():
    return compute_indicator(registry.get("UNEMPB"), normalized().observations)


def scores():
    return {(s.country_code, s.year): s for s in run().scores}


@pytest.fixture(scope="module")
def dataset_case():
    return load_cases(OBSERVATION_CASES["UNSDG_BENFTS_UNEMP"])


@pytest.fixture(scope="module")
def indicator_case():
    return load_cases(INDICATOR_CASES["UNEMPB"])


# --- UNSDG_BENFTS_UNEMP -------------------------------------------------------------------------


def test_dataset_is_sdg_1_3_1_unemployment_cash_benefit_coverage_both_sexes(dataset_case):
    dataset = CATALOG.dataset("UNSDG_BENFTS_UNEMP")
    assert (dataset.source.organization_code, dataset.source.query_code, dataset.source.organization_series_code) == ("UNSDG", "1.3.1", "SI_COV_UEMP")
    assert dataset.source.dimensions == {"sex": "BOTHSEX"} == dataset_case["dimensions"] and dataset_case["series_code"] == "SI_COV_UEMP"
    assert dataset.unit == "PERCENT" == {o["unit"] for o in dataset_case["observations"]}.pop() and "UNSDG_BENFTS_UNEMP" in SUPPORTED_DATASETS
    uemp = [r for r in rows() if r["series"] == "SI_COV_UEMP"]
    assert {r["age"] for r in uemp} == {"15+"} and {r["units"] for r in uemp} == {"PERCENT"}  # one age group, one unit: sex is the only slicing dimension
    assert {r["seriesDescription"] for r in uemp} == {"[ILO] Proportion of unemployed persons receiving unemployment cash benefit, by sex (%)"}  # the ILO is the custodian agency


def test_only_the_both_sexes_slice_of_the_one_series_is_kept():
    result = normalized()
    assert {o.provenance["source_series"] for o in result.observations} == {"SI_COV_UEMP"}
    assert {o.provenance["source_dimensions"]["sex"] for o in result.observations} == {"BOTHSEX"}
    austria = {(r["sex"], json.loads(r["years"])[-1]["value"]) for r in rows() if r["series"] == "SI_COV_UEMP" and r["geoAreaName"] == "Austria"}
    assert {sex for sex, _ in austria} == {"BOTHSEX", "FEMALE", "MALE"}  # the fixture holds all three slices for Austria
    assert len({o.year for o in result.observations if o.country_code == "AUT"}) == 13  # one value per year, not three
    # Iceland has rows in other 1.3.1 series (here SI_COV_BENFTS) but none in SI_COV_UEMP
    assert any(r["geoAreaName"] == "Iceland" for r in rows()) and not any(o.country_code == "ISL" for o in result.observations)


def test_coverage_zeros_aggregates_and_kosovo(dataset_case):
    result = normalized()
    assert len(result.observations) == 106 and len({o.country_code for o in result.observations}) == 16
    assert (min(o.year for o in result.observations), max(o.year for o in result.observations)) == (2000, 2024)  # no year filter
    assert sorted(code for code, _ in result.skipped_areas) == ["1", "150", "412"]  # World, Europe and Kosovo (no ISO 3166 code): legacy dropped them too
    assert result.missing_values == dataset_case["empty_source_values"] == 918
    zeros = sorted((o.country_code, o.year) for o in result.observations if o.value == 0)
    assert {c for c, _ in zeros} == {"ETH", "IND", "NGA", "SGP"} and len(zeros) == 18  # reported zeros are values, as in legacy
    assert {o.provenance["nature"] for o in result.observations} == {"E"}  # every value is an estimate; kept, never used to filter


# --- UNEMPB -------------------------------------------------------------------------------------


def test_golden_file_records_the_legacy_facts(indicator_case):
    definition = registry.get("UNEMPB")
    definition.check_against(CATALOG)
    assert indicator_case["formula"] == "goalpost(UNSDG_BENFTS_UNEMP, 0, 100)" and indicator_case["methodology_score_function"] == "Score = goalpost(UNSDG_BENFTS_UNEMP, 0, 100)"
    assert indicator_case["goalposts"] == [0, 100] == list(definition.goalposts)
    assert indicator_case["unit"] == "Benefits Coverage (%)" == definition.unit == unempb.UNIT
    assert indicator_case["imputed_unit"] == "Tax Rate" == unempb.IMPUTED_UNIT  # UNEMPB-1
    assert indicator_case["impute_route_exists"] is True and definition.imputes
    assert definition.imputation == SeriesFillThenScore(unempb.score_unempb, (2000, 2023), unit="Tax Rate", listed_recipients=RECIPIENTS)
    assert definition.imputation.steps == ("forward", "backward", "interpolate")  # the order impute_unempb concatenates them
    assert indicator_case["series_fill"] == {"forward_to": 2023, "backward_to": 2000, "interpolation": "every interior gap, any year"}
    assert definition.dataset_codes == ("UNSDG_BENFTS_UNEMP",) and definition.score_dependencies == () and definition.auxiliary_datasets == ()
    assert definition.recipient_group is None  # the recipient is a hard-coded country, not a group


def test_legacy_output_is_consistent_so_exact_parity_is_required(indicator_case):
    assert legacy_inconsistency(indicator_case) is None
    assert indicator_case["legacy_output_conflicts"] == {"observed_and_imputed": [], "duplicate_imputed": []}
    assert not any(code == "UNEMPB" for code, _ in list(INTENTIONAL_DIVERGENCES) + list(PENDING_METHODOLOGY_DECISIONS))


def test_observed_scores_match_the_compute_route(indicator_case):
    result = run()
    assert_parity("UNEMPB observed scores", score_level_records(result.observed_scores), indicator_case["observed_scores"])
    assert len(result.observed_scores) == 106 and not any(is_imputed(s) for s in result.observed_scores)
    assert {s.unit for s in result.observed_scores} == {"Benefits Coverage (%)"}


def test_imputed_scores_match_the_impute_route(indicator_case):
    result = run()
    assert_parity("UNEMPB imputed scores", score_level_records(result.imputed_scores), indicator_case["imputed_scores"])
    assert len(result.imputed_scores) == 304 and all(is_imputed(s) for s in result.imputed_scores)
    assert {s.unit for s in result.imputed_scores} == {"Tax Rate"}


def test_final_identity_set_classification_and_provenance(indicator_case):
    result = run()
    legacy = {(r["country_code"], r["year"]) for key in ("observed_scores", "imputed_scores") for r in indicator_case[key]}
    identities = [(s.country_code, s.year) for s in result.scores]
    assert len(identities) == len(set(identities)) == 410 and set(identities) == legacy and result.unscored == ()
    assert all(s.provenance == {} for s in result.scores)  # imputation is on the input, never on the score
    for s in result.imputed_scores:
        (source,) = s.inputs
        assert source.provenance["imputed"] is True and s.score == unempb.score_unempb(source.value)


def test_higher_coverage_is_better_on_zero_to_one_hundred():
    assert unempb.score_unempb(0) == 0.0 and unempb.score_unempb(50) == 0.5 and unempb.score_unempb(100) == 1.0
    s = scores()
    assert s[("AUT", 2013)].inputs[0].value == 100.0 and s[("AUT", 2013)].score == 1.0  # the upper goalpost, reached
    assert s[("IND", 2019)].inputs[0].value == 0.0 and s[("IND", 2019)].score == 0.0  # a reported zero scores 0
    assert s[("USA", 2019)].score == 27.9 / 100 and s[("AUT", 2019)].score > s[("USA", 2019)].score > s[("MYS", 2019)].score


def test_series_fill_behaviour():
    result = run()
    by_method = Counter(s.inputs[0].provenance["imputation_method"] for s in result.imputed_scores)
    assert by_method == {"Backward Extrapolation": 170, "Linear Interpolation": 86, "Forward Extrapolation": 24, REFERENCE_CLASS_AVERAGE: 24}
    s = scores()
    # Malaysia reports one year (2019): every other year 2000-2023 is that value, carried up to nineteen years back
    malaysia = [s[("MYS", year)] for year in range(2000, 2024)]
    assert {x.inputs[0].value for x in malaysia} == {10.4} and [x.year for x in malaysia if not is_imputed(x)] == [2019]
    assert s[("MYS", 2000)].inputs[0].provenance["imputation_distance"] == 19
    assert s[("AUT", 2001)].inputs[0].provenance["imputation_method"] == "Linear Interpolation"  # 2000-2005 interior gap
    # Colombia's 2024 value is observed and scored; extrapolation stops at 2023 and nothing is carried past it
    assert not is_imputed(s[("COL", 2024)]) and max(x.year for x in result.imputed_scores) == 2023
    assert min(x.year for x in result.imputed_scores) == 2000 and max(x.year for x in result.observed_scores) == 2024


def test_unempb_2_reference_class_is_the_flat_mean_of_every_row_for_iceland(indicator_case):
    observations = normalized().observations
    mean = sum(o.value for o in observations) / len(observations)  # every country, every year, unweighted, zeros included
    reference = indicator_case["reference_class"]
    assert (reference["recipients"], reference["years"], reference["reference_count"], reference["mean"]) == (list(RECIPIENTS), [2000, 2023], 106, mean)
    iceland = [s for s in run().scores if s.country_code == "ISL"]
    assert {s.year for s in iceland} == set(range(2000, 2024)) and all(is_imputed(s) for s in iceland)
    assert {(s.inputs[0].value, s.inputs[0].provenance["reference_observation_count"]) for s in iceland} == {(mean, 106)}
    assert {s.score for s in iceland} == {unempb.score_unempb(mean)}
    assert "ISL" in CountryCatalog.load().group("SSPI67").members


def test_iceland_with_observed_rows_raises_before_scoring():
    iceland = Observation("UNSDG_BENFTS_UNEMP", "ISL", 2019, 60.0, "PERCENT", {})
    with pytest.raises(ImputationError, match=r"\['ISL'\] now have observed UNSDG_BENFTS_UNEMP rows"):
        compute_indicator(registry.get("UNEMPB"), (*normalized().observations, iceland))


def test_an_empty_dataset_raises_as_the_legacy_impute_route_did(indicator_case):
    assert indicator_case["empty_dataset"] == {"observed_scores": [], "legacy_impute_error": "ValueError: Reference data cannot be empty."}
    with pytest.raises(ImputationError, match="reference data for UNSDG_BENFTS_UNEMP/ISL is empty"):
        compute_indicator(registry.get("UNEMPB"), ())
