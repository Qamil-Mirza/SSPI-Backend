def test_c_scores_match_the_legacy_compute_route_on_the_repaired_rows():
    result = run("SECAPP")
    assert_parity("SECAPP scores", score_records(result.observed_scores, imputation=False), CASES["scores"])
    assert len(result.observed_scores) == 56 and result.imputed_scores == () and not any(is_imputed(s) for s in result.scores)
    assert sorted([u.country_code, u.year] for u in result.unscored) == CASES["incomplete_identities"] == []
    scores = {(s.country_code, s.year): s.score for s in result.scores}
    assert scores[("SOM", 2018)] == 0.0 and scores[("FIN", 2018)] == 0.97 and scores[("MYS", 2018)] == 0.375
    assert {y for c, y in scores if c == "MYS"} == set(FSI_EDITIONS)  # edition years only; nothing imputed


