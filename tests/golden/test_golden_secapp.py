"""SECAPP and FSI_SECAPP: what the pinned legacy acquisition does, and parity
of the approved FSI adapter with the executable legacy cleaner and scorer.

``secapp_characterization_cases.json`` records, on a few synthetic records,
the pinned acquisition failing before any FSI value could be stored
(SECAPP-1): the collector parses its address string instead of the page,
the raw shape it stores is not the one the cleaner reads, the source
description it stores is not the one the cleaner queries, and the
registered cleaner's rows have no ``DatasetCode``.

``fsi_secapp_synthetic_cases.json`` and ``secapp_synthetic_cases.json``
were generated by ``generate_public_safety_cases.py`` at the pinned commit
from the committed SYNTHETIC workbooks (invented scores in the three FSI
layouts; the originals are not distributed, GOV-5), in three separate
steps: (A) the pinned registered cleaner on the documents the working
collector of March 2025 stored, and how it fails; (B) the same cleaner
with only the approved repair (surrounding whitespace stripped, five
spellings corrected, the dataset code added), accepted by the legacy clean
collection's validation; (C) the legacy ``compute_secapp`` on those rows.
The new adapter and SECAPP must equal (B) and (C) exactly; no tolerance.
The same comparison on the 18 original workbooks is the opt-in
``test_golden_public_safety_real_data.py``.
"""

