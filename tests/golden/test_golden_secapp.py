def test_b_the_repair_table_is_narrow_and_names_iso_identities():
    registered = APPROVED_SOURCE_CORRECTIONS["FSI_SECAPP"]
    assert APPROVED_NAME_CORRECTIONS == DATASET_CASES["approved_name_corrections"] == registered.name_corrections and registered.confirmed
    assert any("whitespace" in r for r in registered.other_repairs) and any("North Korea" in r and "PRK" in r for r in registered.other_repairs)
    identities = {code: pycountry.countries.get(alpha_3=code).name for code in APPROVED_NAME_CORRECTIONS.values()}
    assert identities == {"CIV": "Côte d'Ivoire", "MKD": "North Macedonia", "FSM": "Micronesia, Federated States of", "PSE": "Palestine, State of", "PRK": "Korea, Democratic People's Republic of"}
    assert country_code("Sri Lanka ") == ("LKA", CORRECTION_DECISION + ": surrounding whitespace stripped") and country_code("Serbia  ")[0] == "SRB"
    assert country_code("South Korea") == ("KOR", None) and country_code("Israel and West Bank") == ("ISR", None) and country_code("Kosovo") == ("XKX", None)


def test_b_observations_equal_the_legacy_cleaners_rows_with_only_the_repair():
    result = normalized()["FSI_SECAPP"]
    assert_parity("FSI_SECAPP observations (approved repair)", [observation_record(o) for o in result.observations], DATASET_CASES["observations"], OBSERVATION_IDENTITY)
    assert len(result.observations) == 56 and result.skipped_areas == () and result.missing_values == 0 and {o.unit for o in result.observations} == {"Index"}
    # every row whose name needed no repair is the pinned cleaner's own row, unchanged
    legacy = Counter((r["country_code"], r["year"], r["value"]) for r in DATASET_CASES["cleaner_output_before_validation"])
    untouched = Counter((o.country_code, o.year, o.value) for o in result.observations if "country_code_correction" not in o.provenance)
    assert not untouched - legacy
    corrected = {(o.provenance["source_country_name"], o.country_code) for o in result.observations if "country_code_correction" in o.provenance}
    assert corrected == {("Cote d'Ivoire", "CIV"), ("Macedonia", "MKD"), ("Micronesia", "FSM"), ("Palestine", "PSE"), ("North Korea", "PRK"), ("Sri Lanka ", "LKA"), ("Serbia  ", "SRB")}


def test_values_years_and_provenance_are_the_sources():
    values = {(o.country_code, o.year): o for o in normalized()["FSI_SECAPP"].observations}
    assert values[("SOM", 2021)].value == 9.932962647670891 and values[("SOM", 2018)].value == 10.0 and values[("FIN", 2018)].value == 0.3  # nothing rounded
    assert values[("CIV", 2021)].provenance["source_country_name"] == "Côte d'Ivoire" and "country_code_correction" not in values[("CIV", 2021)].provenance
    assert values[("PRK", 2023)].value == 8.2 and values[("KOR", 2023)].value == 1.8
    assert values[("MYS", 2018)].provenance["source_year_cell"] == "2018-01-01 00:00:00" and values[("MYS", 2021)].provenance["source_year_cell"] == "2021"
    assert {o.provenance["source_column"] for o in values.values()} == {"C1: Security Apparatus"}  # never the overall total
    assert ("PSE", 2018) not in values  # listed from 2021


@pytest.mark.parametrize("variant", sorted(builder("fsi").VARIANTS))
def test_inputs_the_repair_does_not_cover_are_errors(variant):
    recorded = DATASET_CASES["invalid_variants"][variant]
    assert recorded["legacy_error"] == DATASET_CASES["legacy_clean_error"]
    if variant == "year_not_edition":
        assert recorded["repaired_validation_error"] is None  # legacy would have stored 2020 under the 2021 edition: the adapter's own year check
    else:
        assert recorded["repaired_validation_error"].startswith("InvalidDocumentFormatError")
    error, match = {
        "unapproved_name": (NormalizationError, r"no ISO3 code for \['Atlantis'\]"),
        "duplicate_country": (DuplicateObservationError, "both MYS in FSI 2021"),
        "blank_value": (NormalizationError, "is not a finite number"),
        "year_not_edition": (NormalizationError, "has Year 2020, not the edition year 2021"),
    }[variant]
    with pytest.raises(error, match=match):
        normalize_fsi_dataset(CATALOG.dataset("FSI_SECAPP"), fsi_editions({2021: builder("fsi").build(2021, variant)}))


def test_the_client_downloads_every_pinned_edition_and_refuses_changed_bytes():
    content = fsi_workbook_path(2021).read_bytes()
    pinned = {FSI_KEY: (SourceWorkbook(2021, "https://fsi.invalid/a.xlsx", hashlib.sha256(content).hexdigest()),)}
    requested = []

    def handler(request):
        requested.append(str(request.url))
        return httpx.Response(200, content=content)

    with FSIWorkbookClient(edition_sets=pinned, http=httpx.Client(transport=httpx.MockTransport(handler))) as client:
        editions = client.fetch_editions(FSI_KEY)
    assert requested == ["https://fsi.invalid/a.xlsx"] and editions.workbooks[0].content == content
    with FSIWorkbookClient(http=httpx.Client(transport=httpx.MockTransport(handler))) as client, pytest.raises(SourceResponseError, match="no other edition is substituted"):
        client.fetch_editions(FSI_KEY)  # the default table pins the originals
    with FSIWorkbookClient(http=httpx.Client(transport=httpx.MockTransport(lambda r: httpx.Response(404)))) as client, pytest.raises(SourceRequestError, match="HTTP 404"):
        client.fetch_editions(FSI_KEY)
    with FSIWorkbookClient(edition_sets=pinned, http=httpx.Client(transport=httpx.MockTransport(handler))) as client, pytest.raises(SourceRequestError, match="no FSI edition set"):
        client.fetch_editions("fsi-excel_2024")


