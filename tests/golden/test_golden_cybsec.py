def test_the_local_file_client_refuses_a_missing_or_changed_file(tmp_path):
    with pytest.raises(SourceRequestError, match="not at"):
        LocalFileClient(root=tmp_path).fetch_file(ITU_KEY)
    (tmp_path / "itu").mkdir()
    (tmp_path / "itu" / "gci-local-indicator-summary.csv").write_bytes(ITU_TRANSCRIPTION.read_bytes())  # synthetic bytes, not the pinned ones
    with pytest.raises(SourceResponseError, match="no other version is substituted"):
        LocalFileClient(root=tmp_path).fetch_file(ITU_KEY)
    unpinned = {ITU_KEY: LocalSourceFile("synthetic", "itu/gci-local-indicator-summary.csv", None, "tests")}
    read = LocalFileClient(root=tmp_path, files=unpinned).fetch_file(ITU_KEY)
    assert read.content == ITU_TRANSCRIPTION.read_bytes() and read.sha256 == hashlib.sha256(read.content).hexdigest()
    with pytest.raises(SourceRequestError, match="no local source file is configured"):
        LocalFileClient(root=tmp_path).fetch_file("other")
    assert LocalFileClient().root == DEFAULT_ROOT == REPO_ROOT / "local-data"


