def test_b_corrected_normalization_matches_the_legacy_rows_with_only_the_correction_applied():
    result = normalize_itu_dataset(CATALOG.dataset("ITU_CYBSEC"), itu_file(builder("itu").build("original_unmatched_names")))
    expected = DATASET_CASES["corrected_variants"]["original_unmatched_names"]
    assert_parity("ITU_CYBSEC observations, approved correction", [observation_record(o) for o in result.observations], expected["observations"], OBSERVATION_IDENTITY)
    assert expected["corrections_applied"] == [[name, code] for name, code in sorted(APPROVED_NAME_CORRECTIONS.items())]
    corrected = {o.country_code: o for o in result.observations if "country_code_correction" in o.provenance}
    assert set(corrected) == {"CIV", "MKD", "FSM", "PSE", "VAT"} and corrected["MKD"].provenance["source_country_name"] == "Macedonia"
    assert {o.provenance["country_code_correction"] for o in corrected.values()} == {CORRECTION_DECISION}
    values = {(o.country_code, o.year): o.value for o in result.observations}
    assert values[("CIV", 2014)] == 0.1 and values[("MKD", 2024)] == 0.5125 and values[("FSM", 2020)] == 0.0 and ("VAT", 2014) not in values  # scaling unchanged; blank stays missing


