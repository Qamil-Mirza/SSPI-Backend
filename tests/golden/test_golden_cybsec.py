def test_scores_match_the_compute_route_exactly():
    result = run("CYBSEC")
    assert_parity("CYBSEC scores", score_records(result.observed_scores, imputation=False), CASES["scores"])
    assert len(result.observed_scores) == 56 and result.imputed_scores == () and not any(is_imputed(s) for s in result.scores)
    assert sorted([u.country_code, u.year] for u in result.unscored) == CASES["incomplete_identities"] == []
    scores = {(s.country_code, s.year): s.score for s in result.scores}
    assert scores[("MYS", 2020)] == 0.9986 and scores[("MYS", 2024)] == 1.0 and scores[("ISL", 2014)] == 0.0
    assert not any((c, y) in scores for c in ("MYS", "AUT", "USA") for y in (2015, 2016, 2019, 2021, 2022, 2023))  # edition years only


