def test_only_2020_and_2024_are_divided_by_100_and_values_keep_ten_decimals():
    """CYBSEC-2: the legacy cleaner rescales the two editions published on 0-100 and stores at most ten decimals."""
    assert DIVIDED_BY_100 == ("2024", "2020")
    values = {(o.country_code, o.year): o for o in normalized()["ITU_CYBSEC"].observations}
    assert values[("MYS", 2020)].value == 0.9986 and values[("MYS", 2024)].value == 1.0 and values[("USA", 2024)].value == 0.9747  # 97.47 / 100 is 0.9746999999999999
    assert values[("VNM", 2018)].value == 0.123456789 and values[("VNM", 2020)].value == 0.3333333333  # to_json kept ten decimals
    assert values[("USA", 2014)].value == 0.5 and not values[("USA", 2014)].provenance["divided_by_100"] and values[("USA", 2024)].provenance["divided_by_100"]
    assert values[("USA", 2024)].provenance["source_value"] == "97.47" and values[("ISL", 2014)].value == 0.0  # a published zero is kept
    assert ("MYS", 2017) not in values and not any(o.country_code == "VAT" for o in values.values())  # blank cells are missing


