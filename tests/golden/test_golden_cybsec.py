"""Parity for ITU_CYBSEC and CYBSEC against the pinned legacy collector,
cleaner and compute route, on the committed SYNTHETIC transcription
(invented scores in the layout of the legacy hand transcription of the ITU
Global Cybersecurity Index; the original is not distributed, GOV-4):
observations, the selective division by 100, the legacy name matcher,
missing values, the legacy invalid-input failures, scores, and the legacy
score function on inputs no fixture holds. The approved correction of five
country names (CYBSEC-1) is tested in three separate steps: (A) the legacy
failure it repairs, (B) normalization with only the correction applied,
equal to the legacy cleaner's own rows with the correction applied, and (C)
the legacy compute route's scores on those rows. Also what the pinned code does
with the path it reads (the file is not there at the pinned commit).

``itu_cybsec_synthetic_cases.json`` and ``cybsec_synthetic_cases.json`` were
generated by ``generate_public_safety_cases.py`` in the old virtualenv at
the pinned commit. Every comparison is exact; no tolerance. What the legacy
cleaner and the new adapter do with the original transcription is the
opt-in ``test_golden_public_safety_real_data.py``.
"""

