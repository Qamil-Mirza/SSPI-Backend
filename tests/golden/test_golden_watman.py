@pytest.mark.parametrize("name", list(VARIANTS))
def test_observed_scores_match_the_compute_route(name):
    """The compute route has no imputation, so it is checked on both variants with a strategy-free definition."""
    from sspi.indicators import IndicatorDefinition
    from sspi.indicators.watman import score_watman

    variant = VARIANTS[name]
    observations, _ = inputs_for(name)
    observed = compute_indicator(IndicatorDefinition("WATMAN", score_watman, imputation=None), observations)
    assert_parity(f"WATMAN observed scores ({name})", score_records(observed.observed_scores, imputation=True), variant["scores"])
    assert sorted({(u.country_code, u.year) for u in observed.unscored}) == [tuple(i) for i in variant["incomplete_identities"]]
    assert not any(is_imputed(s) for s in observed.observed_scores)


def test_observed_pass_is_identical_with_the_strategy_attached(result):
    variant = VARIANTS["sgp_without_2005"]
    assert_parity("WATMAN observed scores (with strategy)", score_records(result.observed_scores, imputation=True), variant["scores"])


def test_imputed_scores_match_the_impute_route(result):
    variant = VARIANTS["sgp_without_2005"]
    assert variant["legacy_impute_error"] is None
    assert_parity("WATMAN imputed scores", score_records(result.imputed_scores, imputation=True), variant["imputed_scores"])
    assert len(result.imputed_scores) == 78
    assert sorted({(u.country_code, u.year) for u in result.unscored}) == [tuple(i) for i in variant["imputed_incomplete_identities"]] == []
    assert all(is_imputed(s) for s in result.imputed_scores) and not any(is_imputed(s) for s in result.observed_scores)
    assert {(s.country_code, s.year) for s in result.observed_scores}.isdisjoint({(s.country_code, s.year) for s in result.imputed_scores})


def test_headline_imputation_paths(result):
    by_country = {}
    for s in result.imputed_scores:
        by_country.setdefault(s.country_code, []).append(s)
    che = {s.year: s for s in by_country["CHE"]}
    sgp = {s.year: s for s in by_country["SGP"]}
    assert sorted(che) == list(range(2000, 2024)) and sorted(sgp) == list(range(2000, 2024))
    che_cwueff = next(o for o in che[2010].inputs if o.dataset_code == "UNSDG_CWUEFF")
    assert che_cwueff.provenance["imputation_method"] == SYNTHETIC_METHOD and che_cwueff.provenance["derived_from"] == "UNSDG_WUSEFF"
    sgp_cwueff = next(o for o in sgp[2010].inputs if o.dataset_code == "UNSDG_CWUEFF")
    assert sgp_cwueff.provenance["imputation_method"] == "ImputeReferenceClassAverage"
    # countries with a derived series get only the extrapolated 2000-2005 years imputed
    mys = sorted(s.year for s in by_country["MYS"])
    assert mys == list(range(2000, 2006))
    assert all(o.provenance.get("imputation_method") == "Backward Extrapolation" for s in by_country["MYS"] for o in s.inputs if o.dataset_code == "UNSDG_CWUEFF")
