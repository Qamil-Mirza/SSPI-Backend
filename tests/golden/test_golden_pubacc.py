"""Parity for WB_PUBACC and PUBACC against the legacy cleaner and the legacy
compute route on the committed World Bank sample: observations, skipped
areas, scores, unit, inputs, survey-wave years, and the legacy score
function on inputs the sample does not hold.

``wb_pubacc_cases.json`` and ``pubacc_cases.json`` were generated by
``generate_financial_cases.py`` in the old virtualenv at the pinned commit,
running the registered legacy cleaner and the ``compute_pubacc`` view
function. Legacy PUBACC has no impute route. Every comparison is exact; no
tolerance.
"""

from collections import Counter

import pytest

from sspi.imputation import is_imputed
from sspi.indicators import compute_indicator, pubacc, registry
from sspi.ingestion.runner import SUPPORTED_DATASETS
from tests.golden.financial import CATALOG, normalized, rows
from tests.golden.parity import INDICATOR_CASES, OBSERVATION_CASES, OBSERVATION_IDENTITY, assert_parity, load_cases, observation_record, score_records

DATASET_CASES = load_cases(OBSERVATION_CASES["WB_PUBACC"])
CASES = load_cases(INDICATOR_CASES["PUBACC"])
WAVES = {2011, 2014, 2017, 2021, 2022, 2024}


@pytest.fixture(scope="module")
def result():
    return compute_indicator(registry.get("PUBACC"), normalized()["WB_PUBACC"].observations)


def test_dataset_is_findex_account_ownership_among_adults():
    dataset = CATALOG.dataset("WB_PUBACC")
    assert DATASET_CASES["source_indicator"] == "FX.OWN.TOTL.ZS" == dataset.source.query_code == dataset.source.organization_series_code
    assert "WB_PUBACC" in SUPPORTED_DATASETS and dataset.unit == "Percent"  # the cleaner's literal (PROVENANCE)
    assert DATASET_CASES["descriptions"] == ["Account ownership at a financial institution or with a mobile-money-service provider (% of population ages 15+)"]


def test_observations_match_the_legacy_cleaner_exactly():
    result_ = normalized()["WB_PUBACC"]
    assert_parity("WB_PUBACC observations", [observation_record(o) for o in result_.observations], DATASET_CASES["observations"], OBSERVATION_IDENTITY)
    assert [list(s) for s in result_.skipped_areas] == DATASET_CASES["skipped_areas"]
    assert result_.missing_values == DATASET_CASES["empty_source_values"] == 995 and len(result_.observations) == 61
    assert not any(r["value"] == 0 for r in rows("FX.OWN.TOTL.ZS"))


def test_only_survey_wave_years_are_published():
    years = Counter(o.year for o in normalized()["WB_PUBACC"].observations)
    assert set(years) == WAVES and years[2022] == 2  # 2022 fieldwork: DR Congo and Mexico in this sample
    assert sorted(o.country_code for o in normalized()["WB_PUBACC"].observations if o.year == 2022) == ["COD", "MEX"]


def test_golden_file_records_the_legacy_facts():
    definition = registry.get("PUBACC")
    definition.check_against(CATALOG)
    assert CASES["formula"] == "goalpost(WB_PUBACC, 0, 100)" and CASES["methodology_score_function"] == "Score = goalpost(WB_PUBACC, 0, 100)"
    assert CASES["goalposts"] == [0, 100] == list(definition.goalposts)
    assert CASES["unit"] == pubacc.UNIT == definition.unit == "Percent"
    assert CASES["impute_route_exists"] is False and not definition.imputes
    assert definition.dataset_codes == ("WB_PUBACC",) and definition.score_dependencies == () and definition.auxiliary_datasets == ()


def test_scores_match_the_compute_route_exactly(result):
    assert_parity("PUBACC scores", score_records(result.observed_scores, imputation=False), CASES["scores"])
    assert len(result.observed_scores) == 61 and {s.unit for s in result.scores} == {"Percent"}


def test_nothing_is_imputed_or_interpolated_between_waves(result):
    assert result.imputed_scores == () and result.unscored == () and CASES["incomplete_identities"] == []
    assert not any(is_imputed(s) for s in result.scores) and {s.year for s in result.scores} == WAVES
    assert {s.year for s in result.scores if s.country_code == "MYS"} == {2011, 2014, 2017, 2021, 2024}


def test_scores_are_the_share_of_adults_with_an_account(result):
    s = {(x.country_code, x.year): x.score for x in result.scores}
    assert s[("MYS", 2024)] == 0.8869180124211159 and s[("AUT", 2024)] == 0.995084974640411 and s[("USA", 2024)] == 0.970230983290589
    assert s[("DNK", 2021)] == s[("NOR", 2014)] == 1.0  # published as exactly 100
    assert s[("TKM", 2011)] == 0.404911517118832 / 100  # the smallest value


@pytest.mark.parametrize("case", CASES["score_function_cases"], ids=lambda c: c["case"])
def test_the_score_function_matches_the_legacy_closure_on_edge_inputs(case):
    assert pubacc.score_pubacc(**case["inputs"]) == case["score"]


def test_an_empty_dataset_scores_nothing():
    assert CASES["empty_dataset"]["observed_scores"] == [] and compute_indicator(registry.get("PUBACC"), ()).scores == ()
