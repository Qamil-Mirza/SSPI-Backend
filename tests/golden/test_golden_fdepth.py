"""Parity for WB_CREDIT, WB_DPOSIT and FDEPTH against the legacy cleaners and
the legacy compute route on the committed World Bank samples: observations,
skipped areas, scores, unit, inputs, incomplete groups, and the legacy score
function on inputs the samples do not hold. Also the recorded behaviour of
the legacy impute route, which raises on every input (FDEPTH-1), and the
new backend's reproduction of what legacy stored: observed scores only.

``wb_credit_cases.json``, ``wb_dposit_cases.json`` and ``fdepth_cases.json``
were generated by ``generate_financial_cases.py`` in the old virtualenv at
the pinned commit, running the registered legacy cleaners and the
``compute_fdepth`` / ``impute_fdepth`` view functions. Every comparison is
exact; no tolerance.
"""

from collections import Counter

import pytest

from sspi.imputation import is_imputed
from sspi.indicators import compute_indicator, fdepth, registry
from sspi.ingestion.runner import SUPPORTED_DATASETS
from sspi.metadata import CountryCatalog
from sspi.scoring import UnscoredReason
from tests.golden.financial import CATALOG, SERIES, normalized, rows
from tests.golden.parity import INDICATOR_CASES, INOPERATIVE_IMPUTE_ROUTES, OBSERVATION_CASES, OBSERVATION_IDENTITY, assert_parity, load_cases, observation_record, score_records

CASES = load_cases(INDICATOR_CASES["FDEPTH"])
SSPI67 = set(CountryCatalog.load().group("SSPI67").members)


@pytest.fixture(scope="module")
def result():
    observations = normalized()
    return compute_indicator(registry.get("FDEPTH"), observations["WB_CREDIT"].observations + observations["WB_DPOSIT"].observations)


def scores(result):
    return {(s.country_code, s.year): s for s in result.scores}


# --- WB_CREDIT and WB_DPOSIT --------------------------------------------------------------------


@pytest.fixture(scope="module", params=["WB_CREDIT", "WB_DPOSIT"])
def dataset(request):
    code = request.param
    return code, load_cases(OBSERVATION_CASES[code]), normalized()[code]


def test_datasets_are_the_world_bank_series_the_legacy_collectors_requested(dataset):
    code, case, _ = dataset
    source = CATALOG.dataset(code).source
    assert case["source_indicator"] == SERIES[code] == source.query_code == source.organization_series_code
    assert source.organization_code == "WB" and code in SUPPORTED_DATASETS and CATALOG.dataset(code).unit == "Percent"


def test_observations_match_the_legacy_cleaner_exactly(dataset):
    code, case, result_ = dataset
    assert_parity(f"{code} observations", [observation_record(o) for o in result_.observations], case["observations"], OBSERVATION_IDENTITY)
    assert {o.unit for o in result_.observations} == {"Percent"}  # the cleaner's literal; the API's unit field is empty
    assert {o.provenance["description"] for o in result_.observations} == set(case["descriptions"])


def test_skipped_areas_and_missing_values_match_legacy(dataset):
    code, case, result_ = dataset
    assert [list(s) for s in result_.skipped_areas] == case["skipped_areas"]
    assert result_.missing_values == case["empty_source_values"]
    counts = {"WB_CREDIT": (625, 431, 0), "WB_DPOSIT": (616, 252, 62)}[code]
    assert (len(result_.observations), result_.missing_values, case["rows_without_area_code"]) == counts


def test_the_credit_series_is_wdi_and_its_zeros_are_dropped_as_falsy():
    case = load_cases(OBSERVATION_CASES["WB_CREDIT"])
    assert case["descriptions"] == ["Domestic credit to private sector (% of GDP)"]
    zeros = sorted((r["countryiso3code"], int(r["date"])) for r in rows("FS.AST.PRVT.GD.ZS") if r["value"] == 0)
    assert zeros == [("GNB", 2002), ("ROU", 1993), ("ROU", 1994), ("ROU", 1995)]
    kept = {(o.country_code, o.year) for o in normalized()["WB_CREDIT"].observations}
    assert not kept & set(zeros)  # the shared World Bank cleaner's truthiness test, preserved
    assert {code for code, _ in normalized()["WB_CREDIT"].skipped_areas} == {"AFE", "EUU", "WLD", "XD", "XKX"}


def test_the_deposit_series_is_bank_deposits_from_the_frozen_gfdd_database():
    """FDEPTH-3: GFDD.OI.02 is "Bank deposits to GDP (%)", not financial-system deposits, and ends in 2021."""
    case = load_cases(OBSERVATION_CASES["WB_DPOSIT"])
    assert case["descriptions"] == ["Bank deposits to GDP (%)"] and CATALOG.dataset("WB_DPOSIT").name == "Financial System Deposits"
    observations = normalized()["WB_DPOSIT"].observations
    assert max(o.year for o in observations) == 2021 and not any(o.country_code == "GBR" for o in observations)
    # GFDD serves some economies with no ISO3 code and a two-letter id, which the legacy lookup did not recognize
    assert [list(s) for s in normalized()["WB_DPOSIT"].skipped_areas] == [["CD", "Congo, Dem. Rep."], ["RS", "Serbia"], ["TW", "Taiwan, China"], ["XKX", "Kosovo"]]
    without_code = [r for r in rows("GFDD.OI.02") if not r["countryiso3code"] and not r["country"]["id"]]
    assert len(without_code) == 62 and {r["country"]["value"] for r in without_code} == {"IDA total"}  # ignored, as legacy ignored them


