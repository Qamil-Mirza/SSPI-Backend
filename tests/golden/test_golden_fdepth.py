def test_golden_file_records_the_legacy_facts():
    definition = registry.get("FDEPTH")
    definition.check_against(CATALOG)
    assert CASES["formula"] == "goalpost(WB_CREDIT, 0, 200) / 2 + goalpost(WB_DPOSIT, 0, 100) / 2"
    assert CASES["input_goalposts"] == {"WB_CREDIT": list(fdepth.CREDIT_GOALPOSTS), "WB_DPOSIT": list(fdepth.DEPOSIT_GOALPOSTS)}
    assert CASES["metadata_goalposts"] == [0, 200] and definition.goalposts is None  # FDEPTH-2: the metadata pair is the credit input's only
    assert CASES["score_function_parameters"] == list(definition.dataset_codes) == ["WB_CREDIT", "WB_DPOSIT"]
    assert CASES["unit"] == fdepth.UNIT == definition.unit == "Index"
    assert definition.score_dependencies == () and definition.auxiliary_datasets == ()


def test_observed_scores_match_the_compute_route_exactly(result):
    assert_parity("FDEPTH scores", score_records(result.observed_scores, imputation=False), CASES["observed_scores"])
    assert len(result.observed_scores) == 422 and {s.unit for s in result.scores} == {"Index"}
    assert (min(s.year for s in result.scores), max(s.year for s in result.scores)) == (1960, 2021)  # no year filter; deposits end in 2021


def test_incomplete_groups_match_the_compute_route(result):
    assert sorted([u.country_code, u.year] for u in result.unscored) == CASES["incomplete_identities"]
    assert len(result.unscored) == 397 and {u.reason for u in result.unscored} == {UnscoredReason.MISSING_DATASETS}
    ours = sorted([u.country_code, u.year, sorted(o.dataset_code for o in u.inputs)] for u in result.unscored)
    assert ours == CASES["incomplete_groups"]
    present = Counter(tuple(group[2]) for group in CASES["incomplete_groups"])
    assert present == {("WB_CREDIT",): 203, ("WB_DPOSIT",): 194}


def test_countries_with_only_one_input_are_never_scored_in_those_years(result):
    s = scores(result)
    assert not [k for k in s if k[0] in {"GBR", "SRB", "COD", "SMR"}]  # GBR, SRB and COD have only credit, SMR only deposits
    unscored = {(u.country_code, u.year): u for u in result.unscored}
    assert {y for c, y in unscored if c == "GBR"} == set(range(1960, 2025)) and unscored[("GBR", 2020)].details == ("WB_DPOSIT",)
    assert unscored[("SMR", 2010)].details == ("WB_CREDIT",)
    assert all((c, y) in unscored for c in ("MYS", "AUT") for y in range(2022, 2025))  # credit continues after the deposit series stops
    assert ("ROU", 1995) in unscored and ("ROU", 1996) in s  # a zero credit value was dropped, so the deposit alone is incomplete


def test_nothing_is_imputed(result):
    assert result.imputed_scores == () and CASES["imputed_scores"] == []
    assert not any(is_imputed(s) for s in result.scores) and all(s.provenance == {} for s in result.scores)
    assert not registry.get("FDEPTH").imputes and INOPERATIVE_IMPUTE_ROUTES == {"FDEPTH": "FDEPTH-1"}


def test_scores_are_half_credit_and_half_deposits(result):
    s = scores(result)
    mys = s[("MYS", 2021)]
    v = {o.dataset_code: o.value for o in mys.inputs}
    assert v == {"WB_CREDIT": 127.260894609567, "WB_DPOSIT": 122.5862}
    assert mys.score == (127.260894609567 - 0) / (200 - 0) / 2 + 1.0 / 2 == 0.8181522365239176  # deposits above 100 % clamp to 1
    assert s[("USA", 2020)].score == 1.0  # credit 217 % and deposits 101 %: both clamped
    assert s[("LUX", 2008)].score == 101.153326883708 / 200 / 2 + 0.5  # deposits 462 % of GDP still count as 1
    assert s[("ZWE", 1979)].score == 0.00772579694202912 / 200 / 2 + 0.010706 / 100 / 2  # the smallest values
    assert s[("MYS", 2021)].score > s[("AUT", 2021)].score == 0.7236831867002236


