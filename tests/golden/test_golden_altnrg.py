SSPI67 = tuple(CountryCatalog.load().group("SSPI67").members)
GOLDEN = load_cases(INDICATOR_CASES["ALTNRG"])
DEFINITION = registry.get("ALTNRG")
# dataset -> (legacy product, the IEA's label for it, observations, null values, zero values) on the committed rows
EXPECTED = {
    "IEA_TLCOAL": ("COAL", "Coal and coal products", 258, 4, 0),
    "IEA_NATGAS": ("NATGAS", "Natural gas", 282, 0, 0),
    "IEA_NCLEAR": ("NUCLEAR", "Nuclear", 126, 0, 0),
    "IEA_HYDROP": ("HYDRO", "Hydropower", 249, 0, 0),
    "IEA_GEOPWR": ("GEOTHERM", "Solar, wind and other renewables", 201, 3, 7),
    "IEA_BIOWAS": ("COMRENEW", "Biofuels and waste", 284, 0, 0),
    "IEA_FSLOIL": ("MTOTOIL", "Oil and oil products", 284, 0, 0),
}
COUNTRIES = {"AUT", "BOL", "JPN", "LTU", "MYS", "PAK", "SGP", "USA"}


def records(scores):
    """Golden-file records: score, inputs with their imputation fields, the computed series, the score's own imputation fields."""
    ordered = sorted(scores, key=lambda s: (s.country_code, s.year))
    out = score_level_records(ordered)
    for record, score in zip(out, ordered):
        record["computed"] = [{"dataset_code": c.dataset_code, "value": c.value, "unit": c.unit} for c in score.computed]
    return [{key: record[key] for key in GOLDEN["observed_scores"][0]} for record in out]


def incomplete(groups):
    return sorted(({"country_code": u.country_code, "year": u.year, "datasets": sorted(o.dataset_code for o in u.inputs)} for u in groups), key=lambda r: (r["country_code"], r["year"]))


@pytest.fixture(scope="module")
def result():
    return compute_indicator(DEFINITION, altnrg_observations(), SSPI67)


# --- the seven datasets -------------------------------------------------------------------------


@pytest.mark.parametrize("code", ALTNRG_DATASETS)
def test_dataset_observations_match_the_legacy_cleaner(code):
    case, dataset, normalized = load_cases(OBSERVATION_CASES[code]), MetadataCatalog.load().dataset(code), iea_normalized()[code]
    product, label, count, nulls, zeros = EXPECTED[code]
    assert case["dataset_code"] == code and case["dimensions"] == {"product": product} == dataset.source.dimensions and case["product_label"] == [label]
    assert case["source_request"] == {"url": "https://api.iea.org/stats/indicator/TESbySource", "indicator": "TESbySource"} and dataset.source.query_code == "TESbySource"
    new = [observation_record(o) for o in normalized.observations]
    assert_parity(f"{code} observations", new, case["observations"], OBSERVATION_IDENTITY)
    assert summary(new) == summary(case["observations"]) and len(new) == count
    assert {o.unit for o in normalized.observations} == {"TJ"} == {dataset.unit} and {o.provenance["product"] for o in normalized.observations} == {product}
    assert [area for area, _ in normalized.skipped_areas] == case["skipped_areas"] and "WORLD" in case["skipped_areas"]
    assert (case["empty_source_values"], case["zero_source_values"]) == (nulls, zeros) and normalized.missing_values == nulls + zeros  # nulls and zeros are both dropped


def test_every_source_row_is_an_observation_a_dropped_value_or_a_skipped_area():
    rows = iea_rows()
    assert {r["product"] for r in rows} == {product for product, *_ in EXPECTED.values()} and {r["units"] for r in rows} == {"TJ"} and {r["flow"] for r in rows} == {"TES"}
    kept = sum(len(n.observations) for n in iea_normalized().values())
    dropped = sum(n.missing_values for n in iea_normalized().values())
    skipped = sum(1 for r in rows if r["country"] in ("WORLD", "GUYANA"))
    assert kept + dropped + skipped == len(rows) == 2034 and (kept, dropped, skipped) == (1684, 14, 336)
    assert {o.country_code for n in iea_normalized().values() for o in n.observations} == COUNTRIES  # Guyana is published as "GUYANA", not an ISO code: dropped, as in legacy
    assert (min(int(r["year"]) for r in rows), max(int(r["year"]) for r in rows)) == (1990, 2025)


