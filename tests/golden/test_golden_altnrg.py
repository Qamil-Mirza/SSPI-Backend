"""Parity for the seven IEA datasets and for ALTNRG against the legacy
cleaners and BOTH legacy routes, on the committed ``TESbySource`` rows.

``iea_*_cases.json`` and ``altnrg_cases.json`` were generated by
``generate_iea_cases.py`` in the old virtualenv at the pinned commit,
running the registered cleaners and the ``compute_altnrg`` /
``impute_altnrg`` view functions themselves. Every comparison is exact; no
tolerance.
"""

